/** One argument read back as the string it was given as, or `null`. */
function argText(args: RunArgs, key: string): string | null {
  const value = args[key];
  if (value === undefined) return null;
  return typeof value === 'string' ? value : String(value);
}

/** One argument read back as a number, or `null`. */
function argInt(args: RunArgs, key: string): number | null {
  const value = args[key];
  return typeof value === 'number' ? value : null;
}

/** The string array a boundary value carries, or the fallback when it is not one. */
function stringList(value: unknown, fallback: readonly string[]): readonly string[] {
  const list = asArray(value);
  if (!list) return fallback;
  return list.filter((entry): entry is string => typeof entry === 'string');
}

/** The numeric fields a case's limits/budget JSON carries, as finite numbers. */
function numberRecord(source: Record<string, unknown> | undefined): Record<string, number> {
  const out: Record<string, number> = {};
  for (const [key, value] of Object.entries(source ?? {})) {
    if (typeof value === 'number' && Number.isFinite(value)) out[key] = value;
  }
  return out;
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  for (const key of ['budget-scale', 'max-role-turns']) {
    const value = args[key];
    if (value !== undefined && (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 1)) {
      throw new Error(`--${key} must be a positive integer`);
    }
  }
  const caseDef = loadCase(argText(args, 'case'));
  const requestedMode = argText(args, 'mode');
  const runIds = requestedMode === 'all' ? ['single', 'flat', 'hierarchical'] : [requestedMode ?? 'hierarchical'];
  const baseRunId = argText(args, 'run-id');
  if (baseRunId === null) throw new Error('--run-id must be a string');
  const summaries: RunResult[] = [];
  for (const mode of runIds) {
    const runId = runIds.length > 1 ? `${baseRunId}-${mode}` : baseRunId;
    summaries.push(await runOnce({ args, caseDef, mode, runId }));
  }
  const failed = summaries.filter(summary => summary.scenario_status !== 'PASSED');
  console.log(JSON.stringify({ case: caseDef.id, runs: summaries }, null, 2));
  if (failed.length && !args['keep-failed']) process.exitCode = 1;
}

function parseArgs(argv: readonly string[]): RunArgs {
  const out: RunArgs = { mode: 'hierarchical', 'timeout-ms': undefined };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === undefined || !token.startsWith('--')) continue;
    const key = token.slice(2);
    const next = argv[index + 1];
    if (next === undefined || next.startsWith('--')) out[key] = true;
    else {
      out[key] = /^-?\d+$/.test(next) ? Number(next) : next;
      index += 1;
    }
  }
  return out;
}

/**
 * The only case-level environment a case may set. Isolation (`HOME`, `TMPDIR`,
 * `DSH_HOME`), the data directory, the workspace and the model route are owned
 * by the runner: a case that could redirect them would stop being a case and
 * start being a different experiment.
 */
export { CASE_ENV_KEYS };

export function validateCaseEnv(caseDef: CaseDefinition): Record<string, string> {
  const env = caseDef.env ?? {};
  if (typeof env !== 'object' || Array.isArray(env)) throw new Error(`case ${caseDef.id}: env must be an object`);
  const unknown = Object.keys(env).filter(key => !CASE_ENV_KEYS.includes(key));
  if (unknown.length) {
    throw new Error(`case ${caseDef.id}: env may only set ${CASE_ENV_KEYS.join(', ')}; got ${unknown.join(', ')}`);
  }
  for (const [key, value] of Object.entries(env)) {
    if (typeof value !== 'string' || !value) throw new Error(`case ${caseDef.id}: env.${key} must be a non-empty string`);
  }
  return { ...env };
}

