/**
 * A fatal live-check error cannot be repaired by waiting for the cluster to
 * settle: the panel fixture may be holding a request until that check clicks
 * Cancel. Preserve the evidence and propagate to runOnce's existing cleanup
 * and failed-report path. Ordinary failed assertions still run to completion.
 */
/** The one thing the live-check collector itself needs: the report it writes. */
export interface LiveCheckTarget {
  report: LiveCheckReport;
}

export async function runLiveChecks<T extends LiveCheckTarget>(
  check: (context: T) => Promise<LiveChecks>,
  context: T,
): Promise<LiveChecks> {
  const { report } = context;
  let outcome: LiveChecks;
  try {
    outcome = await check(context);
  } catch (error) {
    report.live_checks = { checks: [], error: messageOf(error) };
    report.notes.push(`live checks failed: ${messageOf(error)}`);
    throw error;
  }
  report.live_checks = outcome;
  const blocked = outcome.blocked ?? [];
  if (outcome.error || blocked.length) {
    const error = new Error(outcome.error ?? `live checks blocked: ${blocked.join(', ')}`);
    report.notes.push(`live checks failed: ${error.message}`);
    throw error;
  }
  return outcome;
}

function hashText(text: string | Buffer): string {
  return `sha256:${createHash('sha256').update(text).digest('hex')}`;
}

function hashFile(path: string): string | null {
  return existsSync(path) ? hashText(readFileSync(path)) : null;
}

/**
 * One digest over every file of one or more source trees, plus the file count.
 *
 * Paths are made relative to the tree, so the fingerprint describes the sources
 * and their layout rather than the directory this checkout happens to live in:
 * the same commit verified from a second checkout must produce the same digest,
 * and an absolute path would make every recorded hash unverifiable anywhere
 * else. An `extra` tree is folded into the same digest under its own prefix, so
 * sources that live in a second directory are still covered — and a name in one
 * tree never aliases a name in the other.
 */
export function hashTree(root: string, extra: readonly { prefix: string; root: string }[] = [], filter?: (relativePath: string) => boolean): HashTree {
  const files: Array<{ path: string; digest: string | null }> = [];
  for (const tree of [{ prefix: '', root }, ...extra]) {
    if (!existsSync(tree.root)) return { digest: null, files: 0 };
    for (const entry of walk(tree.root)) {
      const path = relative(tree.root, entry.path).split(sep).join('/');
      if (filter && !filter(path)) continue;
      files.push({ path: tree.prefix ? `${tree.prefix}/${path}` : path, digest: hashFile(entry.path) });
    }
  }
  files.sort((a, b) => a.path.localeCompare(b.path));
  const digest = hashText(files.map(entry => `${entry.path}:${entry.digest}`).join('\n'));
  return { digest, files: files.length };
}

/**
 * The code fingerprint of one run: the plugin sources, both built entry points,
 * the case file and every patch the host loads. It is what makes "the same
 * build" a checkable claim instead of an assumption.
 */
/**
 * Which part of the build fingerprint moved between two samples, or null when
 * the run describes one single build. Kept as a named function because the
 * claim "this report describes one build" is only checkable if the rule that
 * decides it is itself checkable.
 */
export function buildDrift(before: BuildHashes | null | undefined, after: BuildHashes | null | undefined): string | null {
  if (!before || !after) return 'the fingerprint was never taken';
  const changed = [];
  for (const key of [
    'plugin_source', 'lib_index', 'lib_client', 'lib_tools', 'lib_web',
    'typert_host', 'typert_host_types', 'typert_remote_client', 'typert_remote_client_types',
    'host_source', 'acceptance_source', 'case_file',
  ]) {
    if (JSON.stringify(before[key] ?? null) !== JSON.stringify(after[key] ?? null)) changed.push(key);
  }
  const beforePatches = JSON.stringify(before.patches ?? []);
  if (beforePatches !== JSON.stringify(after.patches ?? [])) changed.push('patches');
  return changed.length ? changed.join(', ') : null;
}

/** The package that carries the plugin's sources and build outputs. */
const PLUGIN_ROOT = join(PROJECT_ROOT, 'packages/dsh-flow');

/**
 * The code fingerprint of one run: the plugin sources, its built entry points,
 * both generated Typert artifact pairs, the dev chain, the case file and every
 * patch the host loads. It is what makes "the same build" a checkable claim
 * instead of an assumption.
 */
export function computeBuildHashes(caseDef: CaseDefinition, patches: readonly string[]): BuildHashes {
  const lib = join(PLUGIN_ROOT, 'lib');
  return {
    // The plugin's own sources: every `.ts`/`.tsx` the package is built from.
    plugin_source: hashTree(join(PLUGIN_ROOT, 'src'), [], path => path.endsWith('.ts') || path.endsWith('.tsx')),
    host_source: hashTree(join(PROJECT_ROOT, 'src/host'), [
      { prefix: 'scripts', root: join(PROJECT_ROOT, 'scripts') },
    ], path => path.endsWith('.ts')),
    lib_index: hashFile(join(lib, 'index.js')),
    lib_client: hashFile(join(lib, 'client.js')),
    lib_tools: hashFile(join(lib, 'tools.js')),
    lib_web: hashFile(join(lib, 'web.js')),
    typert_host: hashFile(join(lib, 'typert.host.js')),
    typert_host_types: hashFile(join(lib, 'typert.host.d.ts')),
    typert_remote_client: hashFile(join(lib, 'typert.remote-client.js')),
    typert_remote_client_types: hashFile(join(lib, 'typert.remote-client.d.ts')),
    // The acceptance code is part of the experiment: a checker or a scenario
    // that changed mid-run would make the report describe two different tests.
    // The host driver, the mock model, the scenarios and the ledger decide most
    // of what a run proves, so they are covered here too — under the `lib/`
    // prefix they used to live at, which keeps "the acceptance facility" one
    // namespace even though the sources now sit in `src/host/`.
    acceptance_source: hashTree(join(PROJECT_ROOT, 'tests/acceptance'), [
      { prefix: 'lib', root: join(PROJECT_ROOT, 'src/host') },
    ]),
    case_file: caseDef.id ? hashFile(join(CASES_DIR, `${caseDef.id}.json`)) : null,
    patches: (patches ?? []).map(path => ({ path, digest: hashFile(path) })),
  };
}

function loadCase(name: string | null): CaseDefinition {
  if (!name) throw new Error('--case is required');
  const path = join(CASES_DIR, `${name}.json`);
  if (!existsSync(path)) throw new Error(`unknown case ${JSON.stringify(name)}; expected a file at ${path}`);
  const parsed: unknown = JSON.parse(readFileSync(path, 'utf8'));
  return decodeCaseDefinition(parsed, name);
}

async function runOnce({ args, caseDef, mode, runId }: { args: RunArgs; caseDef: CaseDefinition; mode: string; runId: string }): Promise<RunResult> {
  const layout = createRunLayout(ARTIFACTS_ROOT, runId);
  const profile = `dsh-flow-${runId}`.replace(/[^A-Za-z0-9._-]/g, '-');
  if (args.mock) {
    // A mock run fixes the model *input*. An extra model overlay or a
    // budget/turn multiplier would make the verdict describe something other
    // than the frozen fixture the case declares.
    for (const forbidden of ['profile-patch', 'budget-scale', 'max-role-turns']) {
      if (args[forbidden] !== undefined) {
        throw new Error(`--mock refuses --${forbidden}: the mock suite runs the frozen fixture, not a scaled experiment`);
      }
    }
  }
  const mock = args.mock ? await startMockModel({ modelId: MOCK_MODEL_ID }) : null;
  const modelRoute: ModelRoute = mock
    ? { baseURL: mock.baseURL, model: MOCK_MODEL_ID, provider: MOCK_PROVIDER }
    : modelRouteFromEnv();
  const profilePatch = argText(args, 'profile-patch');
  const patches = (caseDef.patches ?? [caseDef.patch ?? 'examples/cluster.patch.yml'])
    .concat(profilePatch === null ? [] : [profilePatch])
    .map(entry => resolve(PROJECT_ROOT, entry));
  if (mock) {
    const overlay = join(layout.root, 'mock-model.patch.yml');
    writeFileSync(overlay, mockPatchText(mock.baseURL));
    patches.push(overlay);
  }
  const bridgeOverlay = join(layout.root, 'ipc-bridge.patch.yml');
  writeFileSync(bridgeOverlay, ipcBridgePatchText());
  patches.push(bridgeOverlay);
  const patch = patches[0];
  const caseEnv = validateCaseEnv(caseDef);
  // The build fingerprint is taken before anything runs and re-checked at the
  // end: a report whose code changed mid-run describes no single build.
  const budgetScale = argInt(args, 'budget-scale') ?? 1;
  const timeoutArg = args['timeout-ms'];
  const settleTimeoutMs = timeoutArg === undefined ? (caseDef.timeout_ms ?? 3_600_000) * budgetScale : timeoutArg;
  if (typeof settleTimeoutMs !== 'number' || !Number.isSafeInteger(settleTimeoutMs) || settleTimeoutMs < 1) {
    throw new Error('settle timeout must be a positive safe integer');
  }
  const buildHashesAtStart = computeBuildHashes(caseDef, patches);

  const started = Date.now();
  const report: AcceptanceReport = {
    run_id: runId,
    case: caseDef.id,
    mode,
    title: caseDef.title,
    started_at: new Date(started).toISOString(),
    validation_mode: mock ? 'mock-api' : 'live-model',
    model_route: modelRoute,
    patch,
    patches,
    profile,
    paths: { ...layout },
    build_hashes: buildHashesAtStart,
    input_hashes: {},
    mechanism_pass: 'UNKNOWN',
    scenario_status: 'UNKNOWN',
    quality_checks: [],
    failure_class: null,
    notes: [],
    ...(budgetScale !== 1 || args['max-role-turns'] !== undefined
      ? { experiment: { budget_scale: budgetScale, max_role_turns: args['max-role-turns'] ?? null, settle_timeout_ms: settleTimeoutMs } }
      : {}),
  };

  const workspace = layout.workspace;
  const preparation = prepareWorkspace(caseDef, workspace, layout);
  report.preparation = preparation;
  // Two different fingerprints, named for what they fingerprint: `input_hashes`
  // is the data the run consumed, `build_hashes` is the code that ran.
  report.input_hashes = preparation.source_hashes ?? {};

  const checksModule = await loadChecksModule(caseDef.id);
  const baselineArgs: BeforeCheckContext = { caseDef, mode, layout, workspace, report, args };
  if (checksModule?.before) report.baseline = await checksModule.before(baselineArgs);

  ensureProfile(layout.home, profile, { bundles: WEB_PROFILE_BUNDLES });
  // Chromium's SingletonSocket uses a Unix-domain pathname with a hard
  // length cap. Keep the actual scratch files under this isolated run, but
  // expose a short, per-run TMPDIR alias to the browser-capable host.
  const browserTmpAlias = caseDef.capabilities?.includes('browser')
    ? join(tmpdir(), `dsh-${randomUUID().slice(0, 12)}`) : null;
  if (browserTmpAlias) {
    symlinkSync(layout.tmp, browserTmpAlias, 'dir');
    report.notes.push(`browser TMPDIR ${browserTmpAlias} -> ${layout.tmp}`);
  }
  const env = buildHostEnv({
    home: layout.home, tmpdir: browserTmpAlias ?? layout.tmp, dataDir: layout.data, workspace, modelRoute,
    modelApiKey: mock ? MOCK_API_KEY : process.env.FLOW_MODEL_API_KEY,
    extra: caseEnv,
  });
  if (mock) {
    report.mock = { scenario: `mock:${caseDef.id}`, base_url: mock.baseURL, model: MOCK_MODEL_ID };
  }

  let host = new DshHost({
    profile,
    patches,
    cwd: workspace,
    env,
    logPath: join(layout.logs, 'host.log'),
  });

  const events: RunEvent[] = [];
  let snapshot: RunSnapshot | null = null;
  let single: SingleReply | null = null;
  let failure: { message: string; stack: string } | null = null;
  try {
    await startAcceptanceHost(host);
    report.notes.push(`host booted (pid ${host.child?.pid}) with profile ${profile}`);
    try {
      await host.waitForWebUrl(120_000);
      report.web_url = host.webUrl;
    } catch (error) {
      report.notes.push(`web URL not observed: ${messageOf(error)}`);
    }
    // The host's own web URL is known before the cluster starts, so a case can
    // name it: the browser case drives the host's authenticated page instead of
    // depending on the public internet.
    const spec = buildSpec(caseDef, workspace, mode, runId, argInt(args, 'dataset-limit'), { webUrl: report.web_url ?? null });
    // A concurrency ladder changes exactly one knob at a time.
    if (args['max-llm-concurrency'] !== undefined) {
      spec.limits = { ...spec.limits, max_llm_concurrency: Number(args['max-llm-concurrency']) };
      const activeAgents = spec.budget.max_active_agents ?? spec.limits.max_active_agents;
      spec.budget = { ...spec.budget, ...(activeAgents === undefined ? {} : { max_active_agents: activeAgents }) };
    }
    if (args['max-active-agents'] !== undefined) {
      spec.limits = { ...spec.limits, max_active_agents: Number(args['max-active-agents']) };
    }
    assertTierBudget(spec);
    delete spec.generated_tier;
    if (budgetScale !== 1) {
      // The case remains an immutable baseline. The effective budget and this
      // override are both written into the report under a new run id; identity
      // and concurrency ceilings stay unchanged.
      for (const dimension of ['tokens', 'model_requests', 'tool_calls', 'wall_time_ms']) {
        const current = spec.budget[dimension] ?? NaN;
        const scaled = current * budgetScale;
        if (!Number.isSafeInteger(scaled)) throw new Error(`scaled ${dimension} is not a safe integer`);
        spec.budget[dimension] = scaled;
      }
    }
    const maxRoleTurns = args['max-role-turns'];
    if (typeof maxRoleTurns === 'number') spec.limits.max_role_turns = maxRoleTurns;
    // Every fixture id is run-scoped before anything is written, so a collision
    // is a clear pre-flight error instead of a half-populated database.
    const namespaced = namespaceFixtures(spec, runId);
    report.fixture_id_map = namespaced.map;
    report.spec = namespaced.spec;
    if (mock) {
      // Bound after namespacing and before `start`: the scenario names the same
      // transactions the case does, and a request that arrives before a script
      // exists is a fixture error rather than a default answer.
      const scenario = buildScenario({
        caseId: caseDef.id, layout, workspace, fixtureIds: namespaced.map, runId, limits: namespaced.spec.limits,
      });
      mock.setScenario(scenario);
      if (report.mock) report.mock.scenario = scenario.name;
    }

    if (mode === 'single') {
      const singleTurn = decodeSingleReply(await host.request('single', undefined, {
        objective: namespaced.spec.objective,
        workspace,
        capabilities: namespaced.spec.capabilities,
        budget: namespaced.spec.budget,
        initial_transactions: namespaced.spec.initial_transactions,
        acceptance_criteria: namespaced.spec.acceptance_criteria,
      }, settleTimeoutMs));
      if (!singleTurn) throw new Error('single reply is not a single-agent result');
      single = singleTurn;
      report.single = singleTurn;
      // The control run is a cluster of its own: report it as such so the
      // ledger and the mechanism gate are computed from the same source.
      report.cluster_id = singleTurn.cluster_id;
    } else {
      const created = decodeStartReply(await host.request('start', undefined, namespaced.spec, 120_000));
      if (!created) throw new Error('start reply carried no cluster');
      report.cluster_id = created.cluster.id;
      if (mock && caseDef.scale_fixture?.concurrency_probe) {
        // Hold exactly `max_llm_concurrency` Worker requests open at once and
        // watch the wire: while they are held, a request beyond the ceiling
        // would have to arrive here. Nothing else can prove the ceiling is
        // enforced rather than merely reported.
        const ceiling = Number(namespaced.spec.limits.max_llm_concurrency ?? 2);
        await mock.waitUntilHeld(ceiling, { barrier: 'scale-concurrency', timeoutMs: 120_000 });
        const beforeProbe = mock.requests.length;
        const probeWindowMs = Number(caseDef.scale_fixture.concurrency_probe_window_ms ?? 3000);
        await new Promise(resolvePromise => setTimeout(resolvePromise, probeWindowMs));
        report.concurrency_probe = {
          ceiling,
          held_simultaneously: mock.heldCount('scale-concurrency'),
          requests_while_held: mock.requests.length - beforeProbe,
          window_ms: probeWindowMs,
        };
        mock.release('scale-concurrency');
      }
      if (caseDef.live_first && checksModule?.live) {
        const liveContext: LiveCheckContext = { caseDef, mode, layout, workspace, report, host, env, args, mock };
        await runLiveChecks(checksModule.live, liveContext);
      }
      if (caseDef.recovery?.require_restart) {
        const outcome = await restartMidFlight({
          host, caseDef, layout, report, args, workspace, profile, patches, env, mock,
        });
        host = outcome.host;
        report.restart = outcome.facts;
      }
      await host.request('settle', created.cluster.id, {
        timeout_ms: settleTimeoutMs,
        poll_ms: 400,
      }, settleTimeoutMs + 120_000);
      snapshot = decodeSnapshot(await host.request('read', created.cluster.id, { include_events: false, limit: 500 }, 120_000));
      events.push(...await drainEvents(host, created.cluster.id));
      report.report = await host.request('report', created.cluster.id, {}, 120_000);
    }
    // Checks that need the live host (the panel, the authenticated route) run
    // before shutdown; everything else runs afterwards from durable state.
    if (!caseDef.live_first && checksModule?.live) {
      const liveContext: LiveCheckContext = { caseDef, mode, layout, workspace, report, host, env, args, snapshot, events, mock };
      await runLiveChecks(checksModule.live, liveContext);
    }
  } catch (error) {
    failure = { message: messageOf(error), stack: error instanceof Error ? error.stack ?? '' : '' };
    report.failure_class = 'MECHANISM';
  } finally {
    if (!args['keep-host']) {
      const stopped = await host.stop();
      report.host_exit = stopped;
    }
    if (browserTmpAlias && !args['keep-host']) unlinkSync(browserTmpAlias);
    if (mock && !args['keep-host']) {
      try {
        report.mock_fixture = { ok: true, ...mock.assertComplete() };
      } catch (error) {
        // A scenario that could not recognise a request, held one that never
        // released, or saw a protocol drift is an *acceptance facility* defect:
        // it fails the run rather than being reported as a plugin outcome.
        report.mock_fixture = { ok: false, problem: messageOf(error), errors: [...mock.errors] };
      }
      report.mock_requests = summarizeMockRequests(mock);
      report.mock_concurrency = {
        peak_concurrent_requests: mock.peakConcurrency(),
        requests: mock.requests.length,
      };
      writeFileSync(join(layout.root, 'mock-requests.json'), `${JSON.stringify(mock.requests.map(entry => {
        const body = asObject(entry.body);
        const messages = asArray(body?.messages) ?? [];
        return {
          seq: entry.seq, at: entry.at, model: entry.model, kind: entry.kind, role: entry.role,
          node_id: entry.node_id, agent_id: entry.agent_id, transaction_id: entry.transaction_id,
          tools: entry.tools, authorized: entry.authorized, request_shape: entry.request_shape,
          digest_source: entry.classified.digest_source ?? null,
          digest_budget: entry.classified.digest?.budget_available ?? null,
          digest_children: Array.isArray(entry.classified.digest?.children_of_node) ? entry.classified.digest.children_of_node.length : null,
          barrier: entry.barrier, held: entry.held, response: entry.response ?? null,
          opened_at: entry.opened_at ?? null, closed_at: entry.closed_at ?? null,
          prompt_preview: entry.classified.userText.slice(0, 1200),
          last_tool_name: entry.classified.lastToolName ?? null,
          last_tool_result: entry.classified.lastToolResult === null || entry.classified.lastToolResult === undefined
            ? null : entry.classified.lastToolResult.slice(0, 600),
          // An unrecognised request is the one case where the full message shape
          // is the evidence needed to fix the fixture; it is never the normal
          // record, which would store the whole session on every run.
          ...(entry.kind === 'unknown' || entry.diagnostic ? {
            diagnostics: messages.map(rawMessage => {
              const message = asObject(rawMessage) ?? {};
              const parts = asArray(message.content);
              return {
                role: message.role,
                tool_calls: Array.isArray(message.tool_calls)
                  ? message.tool_calls.map(call => asObject(asObject(call)?.function)?.name)
                  : undefined,
                text: (typeof message.content === 'string' ? message.content
                  : (parts ?? []).map(part => asString(asObject(part)?.text) ?? '').join('\n')).slice(0, 2000),
              };
            }),
          } : {}),
        };
      }), null, 2)}\n`);
      await mock.close();
    }
  }

  report.failure = failure;

  const ledger = readStoneLedger(layout, report.cluster_id ?? null);
  report.ledger = ledger;

  // The clock and the structured limit evidence are measured *before* the case's
  // checks, because those checks derive their own verdict from them.
  measureRun(report, {
    startedAt: started,
    budget: report.spec?.budget ?? {},
    usage: ledger.usage ?? null,
    clusterReason: ledger.blocked_reason ?? null,
    refusals: ledger.structured_budget_refusals ?? [],
    buildHashes: computeBuildHashes(caseDef, patches),
  });
  const checkResult = await runChecks({ caseDef, mode, layout, workspace, report, single, snapshot, events, host, env, args });
  report.quality_checks = checkResult.checks;
  report.scenario_status = checkResult.scenario_status;
  // A fixture that could not answer a request, or held one that never released,
  // is an acceptance-facility failure. It is never allowed to pass as a plugin
  // outcome, and it is never relabelled as a model-quality result.
  if (report.mock_fixture && report.mock_fixture.ok === false) {
    report.scenario_status = 'FAILED';
    report.failure_class = 'FIXTURE';
  }
  // Classification is finalised before the mechanism verdict is computed, so a
  // check-level MECHANISM failure can never be relabelled by the budget branch.
  // Only a class the checks *derived* is carried here: stamping MODEL_OUTPUT on
  // every unclassified failure before the limit facts were consulted labelled a
  // budget-limited run as a model failure (measured: 16 structured refusals and a
  // `MODEL_OUTPUT` class on the same report).
  if (report.failure_class === null && report.scenario_status === 'FAILED' && checkResult.failure_class) {
    report.failure_class = checkResult.failure_class;
  }
  // The wall clock is *measured here*, before it is classified: passing
  // `report.wall_time_ms` while it is still unset made every wall-time verdict a
  // comparison against zero.
  report.finished_at = new Date().toISOString();
  report.wall_time_ms = Date.now() - started;
  // The same measurement again, now that the checks may have set a class: the
  // measurement is idempotent, and the *class* is what the checks may not
  // overwrite.
  // An explicit budget or wall-time exhaustion is its own verdict: the
  // scenario did not fail because the model was wrong, it stopped because the
  // fixture's own limit was reached.
  const classification = classifyOutcome({
    failureClass: report.failure_class, scenarioStatus: report.scenario_status,
    budget: report.spec?.budget ?? {}, usage: ledger.usage ?? {}, wallTimeMs: report.wall_time_ms,
    clusterReason: ledger.blocked_reason ?? null,
    // Only a *structured* refusal (a persisted budget-refused record with its
    // scope and dimension) is evidence that a limit was really reached. Free
    // text, a near-ceiling ratio or a tool refusal never is.
    refusals: ledger.structured_budget_refusals ?? [],
  });
  report.failure_class = classification.failure_class;
  report.limit_reached = classification.limit_reached;
  report.mechanism_pass = mechanismVerdict(report, ledger);
  if (checkResult.scale_validation) {
    // The plan reads this flag from the report: a tier that did not really run
    // its workers must never be summarised as a verified scale number.
    report.scale_validation = checkResult.scale_validation;
    report.scale_metrics = checkResult.metrics ?? null;
    report.measured_per_file = checkResult.measured_per_file ?? null;
  }
  // A report whose build changed while it ran describes no single build.
  const buildHashesAtEnd = computeBuildHashes(caseDef, patches);
  const drift = buildDrift(report.build_hashes, buildHashesAtEnd);
  report.build_drift = drift;
  if (drift) {
    report.not_comparable = true;
    report.notes.push(`build_hashes changed during the run (${drift}); the report does not describe one build`);
  }

  writeFileSync(join(layout.root, 'report.json'), `${JSON.stringify(report, null, 2)}\n`);
  writeFileSync(join(layout.root, 'events.jsonl'), `${events.map(event => JSON.stringify(event)).join('\n')}\n`);
  writeFileSync(join(layout.root, 'usage.json'), `${JSON.stringify(ledger.usage ?? null, null, 2)}\n`);
  writeFileSync(join(layout.root, 'checks.json'), `${JSON.stringify(checkResult, null, 2)}\n`);
  writeFileSync(join(layout.root, 'sessions.json'), `${JSON.stringify(listSessions(layout), null, 2)}\n`);
  if (snapshot) writeFileSync(join(layout.root, 'state.json'), `${JSON.stringify(snapshot, null, 2)}\n`);

  console.log(`[${runId}] mode=${mode} scenario=${report.scenario_status} mechanism=${report.mechanism_pass} reports=${layout.root}`);
  return {
    run_id: runId,
    mode,
    scenario_status: report.scenario_status,
    mechanism_pass: report.mechanism_pass,
    failure_class: report.failure_class,
    ...(report.wall_time_ms === undefined ? {} : { wall_time_ms: report.wall_time_ms }),
    cluster_id: report.cluster_id ?? null,
    report: join(layout.root, 'report.json'),
  };
}

/** Poll the durable event stream by cursor until the crash trigger or deadline. */
export async function waitForKillEvent(
  host: Pick<DshHost, 'request'>,
  clusterId: string | null,
  killOn: string,
  delay: number,
  {
    now = Date.now,
    sleep = (ms: number) => new Promise<void>(resolvePromise => setTimeout(resolvePromise, ms)),
  }: { now?: () => number; sleep?: (ms: number) => Promise<void> } = {},
): Promise<KillTrigger> {
  const started = now();
  const deadline = started + delay;
  let since = 0;
  let seen = 0;
  let observedSeq: number | null = null;
  let pollError: string | null = null;
  let polls = 0;
  while (now() < deadline) {
    polls += 1;
    try {
      const page = decodeEventsPage(await host.request('events', clusterId ?? undefined, { since, limit: 500 }, 30_000));
      const events = page.events;
      const matches = events.filter(event => event.type === killOn);
      if (matches.length) {
        seen = matches.length;
        observedSeq = matches[0]?.seq ?? null;
        break;
      }
      if (events.length) since = events[events.length - 1]?.seq ?? since;
      // A full page means there may be more durable history already waiting.
      // Catch up before sleeping so the trigger is not lost behind old events.
      if (events.length === 500) continue;
    } catch (error) {
      // A failed poll must not look like "the window never opened".
      pollError = pollError ?? messageOf(error);
      if (polls > 4) break;
    }
    await sleep(250);
  }
  const trigger: KillTrigger = {
    event: killOn, observed: seen, observed_seq: observedSeq, polls, poll_error: pollError,
    cluster_id: clusterId ?? null, observed_at_ms: now() - started,
  };
  if (!seen) {
    trigger.note = pollError
      ? `polling failed (${pollError}); killed on the clock instead`
      : 'the trigger event did not occur before the deadline; killed on the clock instead';
  }
  return trigger;
}

/**
 * Kill the test host mid-flight and restart it against the same DSH_HOME and
 * data directory, capturing the durable facts on both sides of the crash.
 */
async function restartMidFlight({
  host, caseDef, layout, report, args, workspace, profile, patches, env, mock = null,
}: {
  host: DshHost;
  caseDef: CaseDefinition;
  layout: RunLayout;
  report: AcceptanceReport;
  args: RunArgs;
  workspace: string;
  profile: string;
  patches: readonly string[];
  env: Record<string, string | undefined>;
  mock?: MockModelHandle | null;
}): Promise<{ host: DshHost; facts: RestartFacts }> {
  const delay = Number(caseDef.recovery?.kill_after_ms ?? 45_000);
  // A kill-on-event trigger lands the crash *inside* a named window instead of
  // at an arbitrary wall-clock moment. `delivery-flushed` is the one boundary a
  // poll of `messages-injected` cannot reach: the plugin records it after the
  // session is durable and before the delivery is acked.
  const killOn = caseDef.recovery?.kill_on_event ?? argText(args, 'kill-on-event') ?? null;
  // A kill-on-hold trigger is stronger than either: the crash lands while a
  // *named identity is holding a live model request*, proven by the fixture
  // that served it rather than inferred from an event poll.
  const killOnHold = caseDef.recovery?.kill_on_hold ?? argText(args, 'kill-on-hold') ?? null;
  const before = readStoneLedger(layout, report.cluster_id ?? null);
  if (killOnHold) {
    if (!mock) throw new Error(`case ${caseDef.id} requires --mock for its kill-on-hold trigger`);
    const held = await mock.waitForRequest(entry => entry.held && entry.barrier === killOnHold, { timeoutMs: delay });
    report.kill_trigger = {
      event: 'hold', barrier: killOnHold, observed: 1, observed_seq: null, polls: null,
      cluster_id: report.cluster_id ?? null, request_seq: held.seq, kind: held.kind,
      role: held.role, agent_id: held.agent_id, transaction_id: held.transaction_id,
      observed_at_ms: held.at,
    };
  } else if (killOn) {
    report.kill_trigger = await waitForKillEvent(host, report.cluster_id ?? null, killOn, delay);
  }
  const killAtMs = Date.now();
  const stopped = await host.stop({ signal: 'SIGKILL', graceMs: 2000 });
  const atCrash = readStoneLedger(layout, report.cluster_id ?? null);
  // The exact receipts that were dispatched and never settled at the crash: the
  // expected number of UNKNOWN results is this set, not an arbitrary allowance.
  const inFlight = (atCrash.usage_rows ?? []).filter(row => row.settled === null && Number(row.created) <= killAtMs);
  await new Promise(resolvePromise => setTimeout(resolvePromise, Number(caseDef.recovery?.restart_delay_ms ?? 2000)));
  const restarted = new DshHost({ profile, patches, cwd: workspace, env, logPath: join(layout.logs, 'host-restart.log') });
  await startAcceptanceHost(restarted);
  return {
    host: restarted,
    facts: {
      kill_after_ms: delay,
      // The wall clock and the event cursor at the moment of the kill: the
      // crash window is attributed against these, never assumed.
      kill_at_ms: killAtMs,
      event_seq_at_kill: atCrash.event_seq ?? null,
      kill_trigger: report.kill_trigger ?? null,
      exit: stopped,
      usage_at_crash: atCrash.usage ?? null,
      usage_before_kill: before.usage ?? null,
      accepted_at_crash: atCrash.transactions_by_status ?? null,
      uncertain_effects_at_crash: atCrash.effects ?? null,
      leases_at_crash: atCrash.lease_rows ?? null,
      // Receipts dispatched but unsettled, and the transactions that were not
      // yet terminal: the crash's own account of what it interrupted.
      receipts_in_flight_at_crash: inFlight.map(row => ({
        request_id: asString(row.request_id) ?? '',
        agent_id: asString(row.agent_id),
        role: asString(row.role),
        kind: asString(row.kind),
        created: asNumber(row.created),
      })),
      transactions_open_at_crash: (atCrash.transactions_detail ?? []).filter(row => row.status !== 'ACCEPTED'),
      restarted: true,
    },
  };
}

async function loadChecksModule(caseId: string): Promise<ChecksModule | null> {
  const path = join(CHECKS_DIR, `${caseId}.ts`);
  if (!existsSync(path)) return null;
  const loaded: unknown = await import(path);
  return asChecksModule(loaded);
}

/** Narrow a dynamically imported module to the checker surface it exports. */
function asChecksModule(value: unknown): ChecksModule | null {
  const record = asObject(value);
  if (!record) return null;
  const module: ChecksModule = {};
  const before = record.before;
  const live = record.live;
  const run = record.run;
  if (typeof before === 'function') module.before = async context => {
    const result: unknown = await before(context);
    return result;
  };
  if (typeof live === 'function') module.live = async context => {
    const result: unknown = await live(context);
    return decodeLiveChecks(result);
  };
  if (typeof run === 'function') module.run = async context => {
    const result: unknown = await run(context);
    return decodeCheckOutcome(result);
  };
  return module;
}

async function drainEvents(host: DshHost, clusterId: string): Promise<RunEvent[]> {
  const out: RunEvent[] = [];
  let since = 0;
  for (;;) {
    const page = decodeEventsPage(await host.request('events', clusterId, { since, limit: 500 }, 120_000));
    if (!page.events.length) break;
    out.push(...page.events);
    since = page.events[page.events.length - 1]?.seq ?? since;
    if (page.events.length < 500) break;
  }
  return out;
}

function buildSpec(
  caseDef: CaseDefinition,
  workspace: string,
  mode: string,
  runId: string,
  datasetLimit: number | null,
  extra: { webUrl?: string | null } = {},
): RunSpec {
  const limits: Record<string, number> = { ...numberRecord(caseDef.limits), ...(MODE_LIMITS[mode] ?? {}) };
  const budget: Record<string, number> = numberRecord(caseDef.budget);
  if (budget.wall_time_ms === undefined) budget.wall_time_ms = caseDef.timeout_ms ?? 3_600_000;
  const generated = datasetTransactions(caseDef, workspace, datasetLimit);
  if (generated.length) {
    // A scale fixture is the control-plane baseline: one worker per file, no
    // model-authored decomposition, so throughput is not confused with
    // planning ability.
    // The approved V6 tier budget is a function of N, not a ceiling: keeping the
    // case's 1024-tier numbers would let a 16-file canary spend 64x its tier and
    // would not test the limits the plan actually approved.
    budget.tokens = 65536 * generated.length;
    budget.model_requests = 12 * generated.length;
    budget.tool_calls = 16 * generated.length;
    limits.max_agents = Math.max(limits.max_agents ?? 0, generated.length + 32);
    limits.max_role_turns = Math.max(limits.max_role_turns ?? 0, Math.ceil(generated.length / 8) + 16);
    // One Worker may send at most `worker_model_requests` model requests (V6);
    // compaction is accounted separately and does not consume this allowance.
    limits.worker_model_requests = caseDef.scale_fixture?.worker_model_requests ?? 2;
    limits.worker_max_tokens = caseDef.scale_fixture?.worker_max_tokens ?? 512;
  }
  const values = { workspace, runId, webUrl: extra.webUrl ?? '' };
  return {
    objective: substitute(caseDef.objective ?? '', values),
    workspace,
    capabilities: caseDef.capabilities ?? ['fs_read'],
    limits,
    budget,
    ...(generated.length ? { generated_tier: true } : {}),
    ...(generated.length
      ? { initial_transactions: generated }
      : caseDef.initial_transactions
        ? { initial_transactions: caseDef.initial_transactions.map(entry => substituteObject(entry, values)) }
        : {}),
    ...(caseDef.acceptance_criteria ? { acceptance_criteria: caseDef.acceptance_criteria.map(text => substitute(text, values)) } : {}),
    ...(caseDef.delegation ? { delegation: caseDef.delegation.map(entry => substituteObject(entry, values)) } : {}),
    ...(caseDef.message_fixture ? { message_fixture: caseDef.message_fixture.map(entry => substituteObject(entry, values)) } : {}),
    ...(mode === 'flat' ? { notes: 'flat control: root roles plus direct workers, no nested management' } : {}),
  };
}

/** One transaction per dataset entry, capped by the requested ladder step. */
function datasetTransactions(caseDef: CaseDefinition, workspace: string, datasetLimit: number | null): SpecTransaction[] {
  if (!caseDef.dataset) return [];
  const path = join(workspace, caseDef.dataset.file ?? 'dataset.json');
  if (!existsSync(path)) return [];
  const dataset = asObject(JSON.parse(readFileSync(path, 'utf8')));
  const entries = dataset ? asArray(dataset.entries) ?? [] : [];
  const limit = datasetLimit ?? caseDef.scale_fixture?.workers ?? asNumber(dataset?.count) ?? 0;
  return entries.slice(0, limit).map(rawEntry => {
    const entry = asObject(rawEntry) ?? {};
    const relative = asString(entry.path) ?? '';
    const workspacePath = asString(entry.workspace_path) ?? relative;
    return {
      id: `scale-${relative.replace(/[^A-Za-z0-9._-]/g, '_')}`,
      objective: [
        `Read the file ${workspacePath} (relative to the workspace) with the read tool.`,
        'Submit a result object with exactly these fields:',
        `{"file": "${workspacePath}", "symbol": "<one real exported symbol or top-level declaration, copied exactly as it appears>", "line": <line number you saw it on>, "responsibility": "<one sentence>"}`,
        'If the file really has no identifiable symbol, submit {"file": "...", "symbol": "unknown", "reason": "<why>"}.',
      ].join(' '),
      expected_output: 'A result naming a symbol and a line number, or an explicit "unknown".',
      acceptance_criteria: [
        'The result names a symbol that appears in the file, or states unknown with a reason',
        'The result quotes the line number it saw',
      ],
      inputs: { path: relative, file: workspacePath, hash: asString(entry.hash) },
      priority: 0,
    };
  });
}

/**
 * Give every fixture transaction id a run-scoped namespace before `start`.
 *
 * The fixture files use stable ids (`rec-deep`, `panel-tx`) so a case can be
 * read and diffed; two runs must not collide on them. Mapping the ids here —
 * and validating that every reference still resolves — turns a mid-`start`
 * SQLite `UNIQUE constraint failed` into a clear error before anything is
 * written. Ids a case already namespaced by template are left alone.
 */
/** The fixture fields `namespaceFixtures` rewrites, plus whatever else a spec carries. */
export interface FixtureSpecInput {
  initial_transactions?: readonly SpecTransaction[];
  message_fixture?: readonly JsonObject[];
  [key: string]: unknown;
}

/** The namespaced spec, the id map, and the final ids. */
export interface NamespacedFixtures<T> {
  spec: T;
  map: Record<string, string>;
  ids: string[];
}

export function namespaceFixtures(spec: RunSpec, runId: string): NamespacedFixtures<RunSpec>;
export function namespaceFixtures(spec: FixtureSpecInput, runId: string): NamespacedFixtures<FixtureSpecInput>;
export function namespaceFixtures(spec: FixtureSpecInput, runId: string): NamespacedFixtures<FixtureSpecInput> {
  const transactions = spec.initial_transactions ?? [];
  const ids = new Set<string>();
  for (const entry of transactions) {
    if (typeof entry.id === 'string' && entry.id) ids.add(entry.id);
  }
  const map: Record<string, string> = {};
  for (const id of ids) map[id] = id.startsWith(`${runId}-`) ? id : `${runId}-${id}`;
  const mapped = (value: unknown): unknown => (typeof value === 'string' && ids.has(value) ? map[value] : value);
  const mappedList = (value: unknown): unknown => (Array.isArray(value) ? value.map(mapped) : value);
  const namespacedTransactions = spec.initial_transactions?.map(entry => ({
    ...entry,
    id: mapped(entry.id),
    parent_transaction_id: mapped(entry.parent_transaction_id),
    needs: mappedList(entry.needs),
    depends_on: mappedList(entry.depends_on),
  }));
  const namespaced = {
    ...spec,
    ...(namespacedTransactions ? { initial_transactions: namespacedTransactions } : {}),
    ...(spec.message_fixture
      ? { message_fixture: spec.message_fixture.map(entry => ({ ...entry, from: mapped(entry.from), to: mapped(entry.to) })) }
      : {}),
  };
  const finalIds: string[] = [];
  for (const entry of namespaced.initial_transactions ?? []) {
    const objective = 'objective' in entry ? entry.objective : null;
    if (typeof entry.id !== 'string' || !entry.id) throw new Error(`fixture transaction without an id: ${JSON.stringify(objective ?? null)}`);
    finalIds.push(entry.id);
  }
  const duplicates = finalIds.filter((id, index) => finalIds.indexOf(id) !== index);
  if (duplicates.length) throw new Error(`fixture transaction ids are not unique after namespacing: ${[...new Set(duplicates)].join(', ')}`);
  const known = new Set(finalIds);
  for (const entry of namespaced.initial_transactions ?? []) {
    const references = [
      entry.parent_transaction_id,
      ...(Array.isArray(entry.needs) ? entry.needs : []),
      ...(Array.isArray(entry.depends_on) ? entry.depends_on : []),
    ].filter((value): value is string => typeof value === 'string' && value !== '');
    for (const reference of references) {
      if (!known.has(reference)) throw new Error(`fixture transaction ${entry.id} references unknown transaction ${reference}`);
    }
  }
  for (const fixture of namespaced.message_fixture ?? []) {
    for (const endpoint of ['from', 'to'] as const) {
      const value = fixture[endpoint];
      if (typeof value !== 'string' || !known.has(value)) {
        throw new Error(`message fixture ${endpoint} references unknown transaction ${String(value)}`);
      }
    }
  }
  return { spec: namespaced, map, ids: finalIds };
}

/** The fields the tier-budget assertion reads. */
export interface TierBudgetSpec {
  generated_tier?: boolean;
  initial_transactions?: readonly unknown[];
  budget?: Record<string, number>;
}

/**
 * The tier's denominator has exactly one source: the fixture the runner
 * generated. A run whose declared budget is not the function of N it claims is
 * not the tier it reports, so this throws *before* `start` writes anything.
 */
export function assertTierBudget(spec: TierBudgetSpec): void {
  if (spec.generated_tier !== true) return;
  const planned = (spec.initial_transactions ?? []).length;
  const budget = spec.budget ?? {};
  const expected = { tokens: 65536 * planned, model_requests: 12 * planned, tool_calls: 16 * planned };
  for (const [key, value] of Object.entries(expected)) {
    if (budget[key] !== value) throw new Error(`tier budget mismatch: ${key} is ${budget[key]}, expected ${value} for ${planned} planned transactions`);
  }
}

const substitute = (text: string, values: Record<string, unknown>): string => text.replace(
  /\{\{(\w+)\}\}/g,
  (_, key: string) => (values[key] === undefined ? '' : String(values[key])),
);
const substituteObject = <T>(value: T, values: Record<string, unknown>): T => JSON.parse(
  JSON.stringify(value),
  (_key: string, item: unknown) => (typeof item === 'string' ? substitute(item, values) : item),
);

function prepareWorkspace(caseDef: CaseDefinition, workspace: string, layout: RunLayout): Preparation {
  const prep: Preparation = { kind: caseDef.workspace?.kind ?? 'empty', details: [] };
  const config: CaseWorkspaceConfig = caseDef.workspace ?? {};
  if (config.kind === 'generated-corpus') {
    // The scale ladder's corpus is generated into the *run* directory from a
    // fixed recipe: every file, its exported symbol, its line and its content
    // hash are known before the run starts, so "this Worker really read this
    // file and quoted this declaration" is a comparison, not a judgement.
    rmSync(workspace, { recursive: true, force: true });
    mkdirSync(workspace, { recursive: true });
    const generated = generateCorpus(workspace, config);
    prep.details.push(`generated ${generated.count} fixture files in ${generated.dir}`);
    prep.generated_corpus = { dir: generated.dir, count: generated.count, manifest: generated.manifestPath };
  } else if (config.kind === 'seed') {
    if (!config.seed) throw new Error(`case ${caseDef.id}: a seed workspace needs a seed path`);
    const seed = resolve(PROJECT_ROOT, config.seed);
    rmSync(workspace, { recursive: true, force: true });
    const result = spawnSync('cp', ['-a', `${seed}/.`, workspace], { encoding: 'utf8' });
    if (result.status !== 0) throw new Error(`seed copy failed: ${result.stderr}`);
    prep.details.push(`copied seed ${seed}`);
  } else if (config.kind === 'copy-repo') {
    if (!config.source) throw new Error(`case ${caseDef.id}: a copy-repo workspace needs a source path`);
    const source = resolve(config.source);
    rmSync(workspace, { recursive: true, force: true });
    mkdirSync(workspace, { recursive: true });
    const base = ['-a'];
    for (const pattern of stringList(config.exclude, [])) base.push(`--exclude=${pattern}`);
    const attempt = (extra: readonly string[]) => spawnSync('rsync', [...base, ...extra, `${source}/.`, workspace], { encoding: 'utf8', maxBuffer: 1 << 30 });
    // Reflink is a speed optimisation, not a requirement: this rsync build
    // rejects the option, so fall back to a plain copy and record which ran.
    let result = attempt(['--reflink=auto']);
    let copyMode = 'reflink';
    if (result.status !== 0 && /reflink/.test(String(result.stderr))) {
      rmSync(workspace, { recursive: true, force: true });
      mkdirSync(workspace, { recursive: true });
      result = attempt([]);
      copyMode = 'plain';
    }
    if (result.status !== 0) throw new Error(`workspace copy failed (${result.status}): ${result.stderr}`);
    prep.details.push(`rsync (${copyMode}) copy of ${source}`);
    const exclude = stringList(config.hashExclude, ['node_modules', '.git', '.artifacts']);
    const before = buildManifest(source, exclude);
    writeFileSync(join(layout.root, 'source-manifest-before.json'), `${JSON.stringify(before, null, 2)}\n`);
    writeFileSync(join(layout.root, 'source-manifest-meta.json'), `${JSON.stringify({ exclude, taken_at: new Date().toISOString() })}\n`);
    prep.source_hashes = { digest: before.digest, files: before.files, excluded: exclude };
    // A copy that is not isolated must abort here, before any baseline or
    // build command can mutate the workspace.
    prep.copy_integrity = enforceCopyIsolation(source, workspace, {
      allowedRoots: stringList(config.allowedLinkRoots, [
        join(source, 'node_modules'),
        '/home/leo/.cache',
        '/home/leo/.local/share/pnpm',
        '/usr',
        '/opt',
        '/tmp',
      ]),
    });
  } else {
    mkdirSync(workspace, { recursive: true });
  }
  if (config.prepare === 'npm-ci') {
    const result = spawnSync('npm', ['ci', '--ignore-scripts'], { cwd: workspace, encoding: 'utf8', maxBuffer: 1 << 28 });
    prep.npm_ci = { status: result.status, stderr: (result.stderr ?? '').slice(-2000) };
    if (result.status !== 0) throw new Error(`npm ci failed in the case workspace: ${result.stderr}`);
    prep.details.push('npm ci --ignore-scripts');
  }
  if (caseDef.dataset) {
    prep.dataset = buildDataset(caseDef.dataset, workspace);
  }
  return prep;
}

/**
 * Generate the scale ladder's fixed corpus.
 *
 * Deterministic by construction: the file set, each file's exported symbol, the
 * line that declaration sits on and the file's content are all produced here,
 * so the expected answer for every tier transaction exists before any model is
 * asked. The manifest is written beside the corpus, not inside it, so it can
 * never be mistaken for a corpus file.
 */
/** One deterministically generated corpus file. */
interface CorpusManifestEntry {
  path: string;
  symbol: string;
  line: number;
  sha256: string;
}

/** The corpus one scale run generated. */
interface GeneratedCorpus {
  dir: string;
  count: number;
  manifest: readonly CorpusManifestEntry[];
  manifestPath: string;
}

/** The extensions a corpus is selected from when a case names none. */
const CORPUS_FILE_EXTENSIONS: readonly string[] = ['.ts', '.tsx', '.js', '.mjs', '.cjs', '.md', '.json', '.py', '.java', '.go', '.rs'];

function generateCorpus(workspace: string, config: CaseWorkspaceConfig): GeneratedCorpus {
  const dirName = asString(config.dir) ?? 'corpus-src';
  const dir = join(workspace, dirName);
  const count = asNumber(config.count) ?? 64;
  const groups = asNumber(config.groups);
  const manifest: CorpusManifestEntry[] = [];
  mkdirSync(dir, { recursive: true });
  for (let index = 0; index < count; index += 1) {
    const folder = groups ? `group-${String(index % groups).padStart(2, '0')}` : null;
    const name = `module-${String(index).padStart(3, '0')}.js`;
    const relative = folder ? `${folder}/${name}` : name;
    const symbol = `fixtureSymbol${String(index).padStart(3, '0')}`;
    const lines = [
      `// scale fixture module ${index}: generated deterministically for the acceptance run`,
      '// the declaration on the next line is the only symbol a Worker has to find',
      `export function ${symbol}(input) {`,
      `  return input + ${index};`,
      '}',
      '',
    ];
    mkdirSync(dirname(join(dir, relative)), { recursive: true });
    writeFileSync(join(dir, relative), lines.join('\n'));
    manifest.push({
      path: relative, symbol, line: 3,
      sha256: `sha256:${createHash('sha256').update(lines.join('\n')).digest('hex')}`,
    });
  }
  const manifestPath = join(workspace, asString(config.manifest) ?? 'corpus-manifest.json');
  writeFileSync(manifestPath, `${JSON.stringify({ dir: dirName, count, entries: manifest }, null, 2)}\n`);
  return { dir, count, manifest, manifestPath };
}

/** The dataset one scale case materialised. */
interface BuiltDataset {
  path: string;
  corpus: string;
  count: number;
}

/**
 * Build the scale corpus: the selected source files are *copied into the run's
 * workspace* so every worker reads a real file through the host read tool, and
 * the dataset records each file's sha256 and a bounded excerpt.
 */
function buildDataset(config: CaseDataset, workspace: string): BuiltDataset {
  const datasetPath = join(workspace, config.file ?? 'dataset.json');
  const rootText = asString(config.root);
  const root = rootText ? resolve(substitute(rootText, { workspace })) : join(workspace, asString(config.source) ?? 'corpus-src');
  const corpusName = asString(config.corpus) ?? 'corpus';
  const corpus = join(workspace, corpusName);
  const listed = listFiles(root, asNumber(config.limit) ?? 1024, stringList(config.extensions, CORPUS_FILE_EXTENSIONS));
  const excerptBytes = asNumber(config.excerpt_bytes) ?? 4096;
  const entries = listed.map(file => {
    const relative = file.slice(root.length + 1);
    const target = join(corpus, relative);
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(file, target);
    const text = readFileSync(target, 'utf8');
    return {
      path: relative,
      workspace_path: join(corpusName, relative),
      hash: hashFile(target),
      excerpt: text.slice(0, excerptBytes),
    };
  });
  writeFileSync(datasetPath, `${JSON.stringify({ root, corpus: corpusName, count: entries.length, entries }, null, 2)}\n`);
  return { path: datasetPath, corpus, count: entries.length };
}

function listFiles(root: string, limit: number, extensions: readonly string[]): string[] {
  const out: string[] = [];
  const queue = [root];
  const skip = new Set(['.git', 'node_modules', 'dist', 'lib', 'coverage', '.artifacts']);
  while (queue.length && out.length < limit) {
    const current = queue.shift();
    if (current === undefined) break;
    let entries: Dirent[];
    try {
      entries = readdirSync(current, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (out.length >= limit) break;
      if (entry.name.startsWith('.') && entry.name !== '.') continue;
      if (skip.has(entry.name)) continue;
      const full = join(current, entry.name);
      if (entry.isDirectory()) queue.push(full);
      else if (entry.isFile() && extensions.some(extension => entry.name.endsWith(extension))) out.push(full);
    }
  }
  return out.sort();
}

/** One complete path→hash manifest of a tree. */
interface TreeManifest {
  root: string;
  files: number;
  digest: string;
  entries: Record<string, string>;
}

/**
 * Complete path→hash manifest of a tree, excluding only the directory names the
 * caller names. Exclusion is the only knob: a positive glob filter would hash
 * the wrong files.
 */
function buildManifest(root: string, exclude: readonly string[] = []): TreeManifest {
  const entries: Record<string, string> = {};
  const skip = new Set(exclude);
  const walkDir = (dir: string, prefix: string): void => {
    let listing: Dirent[];
    try {
      listing = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of listing) {
      if (skip.has(entry.name)) continue;
      const full = join(dir, entry.name);
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) walkDir(full, relative);
      else if (entry.isFile()) {
        try {
          entries[relative] = createHash('sha1').update(readFileSync(full)).digest('hex');
        } catch {
          entries[relative] = 'unreadable';
        }
      } else if (entry.isSymbolicLink()) {
        entries[relative] = `symlink:${readlinkSync(full)}`;
      }
    }
  };
  walkDir(root, '');
  const names = Object.keys(entries).sort();
  const digest = createHash('sha1');
  for (const name of names) digest.update(`${name}\u0000${entries[name] ?? ''}\n`);
  return { root, files: names.length, digest: digest.digest('hex'), entries };
}

/** One symlink that left the copy's allowed roots. */
interface CopySymlinkLeak {
  link: string;
  target: string;
}

/** What the workspace-isolation gate found. */
interface CopyIntegrity {
  symlinks: {
    total: number;
    absolute: number;
    broken: number;
    outside: CopySymlinkLeak[];
    into_source: CopySymlinkLeak[];
  };
  inodes: { checked: number; shared: string[] };
  allowed_roots: readonly string[];
  source: string;
  copy: string;
}

/**
 * Isolation gate for a copied workspace. It walks the *whole* copy (minus
 * `node_modules`, whose symlinks are the package manager's read-only store
 * links) and aborts on:
 *   - a symlink whose canonical target leaves the copy and the allowed
 *     read-only roots (in particular: resolving back into the source tree);
 *   - a regular file that shares `(dev, ino)` with its source counterpart,
 *     which would make the "copy" a hardlink.
 */
function enforceCopyIsolation(source: string, copy: string, { allowedRoots = [] }: { allowedRoots?: readonly string[] } = {}): CopyIntegrity {
  const canonical = (path: string): string | null => {
    try {
      return realpathSync(path);
    } catch {
      return null;
    }
  };
  const allowed = [...allowedRoots, copy].map(root => root.replace(/\/+$/, ''));
  const symlinks: CopyIntegrity['symlinks'] = { total: 0, absolute: 0, broken: 0, outside: [], into_source: [] };
  const inodes: CopyIntegrity['inodes'] = { checked: 0, shared: [] };
  const queue = [copy];
  const seen = new Set<string>();
  while (queue.length) {
    const dir = queue.pop();
    if (dir === undefined || seen.has(dir)) continue;
    seen.add(dir);
    let listing;
    try {
      listing = readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of listing) {
      const full = join(dir, entry.name);
      const relative = full.slice(copy.length + 1);
      if (entry.isSymbolicLink()) {
        symlinks.total += 1;
        const raw = readlinkSync(full);
        if (raw.startsWith('/')) symlinks.absolute += 1;
        const resolved = canonical(full);
        if (resolved === null) {
          symlinks.broken += 1;
          continue;
        }
        const within = allowed.some(root => resolved === root || resolved.startsWith(`${root}/`));
        if (!within) {
          symlinks.outside.push({ link: relative, target: resolved });
          if (resolved.startsWith(`${source}/`)) symlinks.into_source.push({ link: relative, target: resolved });
        }
      } else if (entry.isDirectory()) {
        if (entry.name === 'node_modules') continue;
        queue.push(full);
      } else if (entry.isFile()) {
        const sourcePath = join(source, relative);
        let sourceStat;
        try {
          sourceStat = statSync(sourcePath);
        } catch {
          continue;
        }
        inodes.checked += 1;
        const copyStat = statSync(full);
        if (sourceStat.dev === copyStat.dev && sourceStat.ino === copyStat.ino) inodes.shared.push(relative);
      }
    }
  }
  const violations = [];
  if (symlinks.into_source.length) {
    violations.push(`${symlinks.into_source.length} symlink(s) resolve into the source repository, e.g. ${symlinks.into_source.slice(0, 3).map(entry => `${entry.link} → ${entry.target}`).join(', ')}`);
  }
  const outsideOnly = symlinks.outside.filter(entry => !entry.target.startsWith(`${source}/`));
  if (outsideOnly.length) {
    violations.push(`${outsideOnly.length} symlink(s) leave the copy and the allowed roots, e.g. ${outsideOnly.slice(0, 3).map(entry => `${entry.link} → ${entry.target}`).join(', ')}`);
  }
  if (inodes.shared.length) {
    violations.push(`${inodes.shared.length} file(s) share an inode with the source (hardlink), e.g. ${inodes.shared.slice(0, 3).join(', ')}`);
  }
  if (violations.length) {
    throw new Error(`workspace copy is not isolated: ${violations.join('; ')}`);
  }
  return { symlinks, inodes, allowed_roots: allowed, source, copy };
}

