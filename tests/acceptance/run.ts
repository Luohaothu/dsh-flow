/** The optional measurements `measureRun` folds into a report. */
export interface MeasureRunOptions {
  startedAt?: number | null;
  clock?: number;
  budget?: Record<string, number> | null;
  usage?: UsageView | null;
  clusterReason?: string | null;
  refusals?: readonly LedgerRow[] | null;
  buildHashes?: BuildHashes | null;
}

/** The usage counters a classification reads. */
export type UsageView = {
  total_tokens?: number | null | undefined;
  requests?: number | null | undefined;
};

/**
 * The measured clock and the structured limit evidence, set on the report
 * *before* the case's own checks run.
 *
 * The scale checks read `report.wall_time_ms` and `report.limit_reached` while
 * they derive their class; measuring both only after they had run left those
 * branches comparing against an unset clock and a null limit, and their verdict
 * was then preserved by the classifier. One measurement, taken once, before.
 */
export interface MeasuredRun {
  failure_class: string | null;
  scenario_status: string | null;
  spec?: { budget: Record<string, number> } | undefined;
  ledger?: { usage?: UsageView | undefined } | undefined;
  finished_at?: string | undefined;
  wall_time_ms?: number | undefined;
  build_hashes?: BuildHashes | null | undefined;
  build_drift?: string | null | undefined;
  not_comparable?: boolean | undefined;
  limit_reached?: LimitReached | null | undefined;
  budget_proximity?: BudgetProximity | undefined;
}

export function measureRun<T extends MeasuredRun>(report: T, {
  startedAt = null, clock = Date.now(), budget = null, usage = null, clusterReason = null, refusals = null, buildHashes = null,
}: MeasureRunOptions = {}): T {
  const finished = clock;
  if (startedAt !== null) {
    report.finished_at = new Date(finished).toISOString();
    report.wall_time_ms = finished - startedAt;
  }
  // The build fingerprint is compared here as well as at the end of the run: the
  // case checks need to know whether the sources moved under them, and they run
  // before the final comparison.
  if (buildHashes) {
    const drift = buildDrift(report.build_hashes, buildHashes);
    report.build_drift = drift;
    if (drift) report.not_comparable = true;
  }
  const classification = classifyOutcome({
    failureClass: report.failure_class ?? null,
    scenarioStatus: report.scenario_status ?? null,
    budget: budget ?? report.spec?.budget ?? {},
    usage: usage ?? report.ledger?.usage ?? null,
    wallTimeMs: report.wall_time_ms ?? 0,
    clusterReason,
    refusals,
  });
  report.limit_reached = classification.limit_reached;
  report.budget_proximity = classification.budget_proximity;
  return report;
}

export function classifyOutcome({
  failureClass, scenarioStatus, budget, usage, wallTimeMs, clusterReason = null, refusals = null,
}: {
  failureClass?: string | null;
  scenarioStatus?: string | null;
  budget: Record<string, number>;
  usage: UsageView | null | undefined;
  wallTimeMs: number;
  clusterReason?: string | null;
  refusals?: readonly LedgerRow[] | null;
}): ClassificationOutcome {
  const tokens = usage?.total_tokens ?? 0;
  const requests = usage?.requests ?? 0;
  // Proximity is *reported*, never used as the cause: 95 of 100 requests leaves
  // five legal sends, and ordinary stagnation can happen there.
  const tokenLimit = budget.tokens ?? Infinity;
  const requestLimit = budget.model_requests ?? Infinity;
  const wallLimit = budget.wall_time_ms ?? Infinity;
  const proximity: BudgetProximity = {
    tokens: tokenLimit === Infinity ? null : Number((tokens / tokenLimit).toFixed(4)),
    requests: requestLimit === Infinity ? null : Number((requests / requestLimit).toFixed(4)),
    wall: wallLimit === Infinity ? null : Number((wallTimeMs / wallLimit).toFixed(4)),
  };
  const structured = Array.isArray(refusals)
    ? refusals.filter(entry => entry && typeof entry.scope === 'string' && entry.scope !== '' && typeof entry.dimension === 'string' && entry.dimension !== '')
    : [];
  // `blockedOnBudget` is only ever derived from structured records: a persisted
  // refusal naming its scope and dimension, or the cluster's own persistent stop
  // reason in its coded form. A model's prose about "exhausting attempts" is not
  // evidence that a budget limit was reached.
  const codedReason = typeof clusterReason === 'string' && /^\s*(BUDGET|LIMIT_REACHED):/.test(clusterReason);
  const blockedOnBudget = structured.length > 0 || codedReason;
  const hitWall = wallTimeMs >= wallLimit;
  const exhausted: LimitExhausted = {
    tokens: budget.tokens !== undefined && tokens >= budget.tokens,
    requests: budget.model_requests !== undefined && requests >= budget.model_requests,
    wall: hitWall,
  };
  const limitReached = Boolean(blockedOnBudget || exhausted.tokens || exhausted.requests || hitWall);
  // A class that a check derived is final: the budget branch may only supply a
  // default when nothing was derived. `limit_reached` carries the structured
  // facts either way, so the tier checks can reach their own verdict.
  const resolved = failureClass ?? (scenarioStatus === 'FAILED' ? (limitReached ? 'LIMIT_REACHED' : 'MODEL_OUTPUT') : null);
  return {
    failure_class: resolved,
    limit_reached: limitReached
      ? {
        hitWall, blockedOnBudget, refusals: structured,
        exhausted, tokens, requests, cluster_reason: clusterReason, proximity,
      }
      : null,
    budget_proximity: proximity,
  };
}

export function mechanismVerdict(report: MechanismReport, ledger: StoneLedger): string {
  const notes: string[] = [];
  const unmeasured: string[] = [];
  const notExercised: string[] = [];
  const record = (verdict: string): string => {
    report.unmeasured_invariants = unmeasured;
    report.not_exercised_invariants = notExercised;
    report.mechanism_notes = notes;
    return verdict;
  };
  // Name every invariant this run could not measure *before* any early return,
  // so an aggregate verdict never implies an unchecked invariant. A run that
  // never created the opportunity is reported as *not exercised* with the
  // reason, which is a different fact from a measurement that failed — and is
  // never silently promoted to a pass.
  if (ledger.cross_scope_writes === null) {
    if (ledger.cross_scope_writes_state === 'not_exercised') {
      notExercised.push(`write-scope enforcement: ${ledger.settled_writes ?? 0} settled write-capable call(s); this scenario's work is read-only, so the write contract is proven by the cases that write`);
    } else {
      unmeasured.push('write-scope enforcement (settled write-capable calls could not all be checked against a granted scope)');
    }
  }
  if (ledger.granted_scope_overlaps === null) unmeasured.push('granted write-scope overlap');
  if (ledger.llm_inflight_over_limit === null) unmeasured.push('LLM in-flight ceiling');
  if (ledger.resident_handles_over_limit === null) unmeasured.push('resident turn-handle ceiling');
  if (report.failure_class === 'MECHANISM') return record('FAIL');
  if ((ledger.duplicate_accepts ?? 0) > 0) notes.push(`duplicate accepts: ${ledger.duplicate_accepts}`);
  if ((ledger.duplicate_charges ?? 0) > 0) notes.push(`duplicate usage charges: ${ledger.duplicate_charges}`);
  if ((ledger.double_leases ?? 0) > 0) notes.push(`double leases: ${ledger.double_leases}`);
  if ((ledger.granted_scope_overlaps ?? 0) > 0) notes.push(`overlapping granted write scopes: ${ledger.granted_scope_overlaps}`);
  if ((ledger.write_scope_refusals ?? 0) > 0) notes.push(`refused out-of-scope writes: ${ledger.write_scope_refusals} (enforcement held)`);
  if ((ledger.cross_scope_writes ?? 0) > 0) notes.push(`writes that escaped their granted scope: ${ledger.cross_scope_writes}`);
  if ((ledger.lost_transactions ?? 0) > 0) notes.push(`transactions without a terminal state: ${ledger.lost_transactions}`);
  if (ledger.resident_handles_over_limit) notes.push('resident turn handles exceeded max_active_agents');
  if (ledger.llm_inflight_over_limit) notes.push('LLM in-flight exceeded max_llm_concurrency');
  // An unmeasured invariant is never evidence of a pass: name it and withhold
  // the aggregate verdict.
  if (!ledger.available) return record('UNKNOWN');
  // Only a defect fails the verdict: a refused write is recorded above as a fact
  // of enforcement, and the note list would otherwise turn it into a failure.
  const defects = notes.filter(note => !/enforcement held/.test(note));
  if (defects.length) return record('FAIL');
  return record(unmeasured.length ? 'UNKNOWN' : 'PASS');
}

/** Read the durable ledger directly from the run's own cluster.sqlite. */
export function readStoneLedger(layout: LedgerLayout, clusterId: string | null): StoneLedger {
  const db = join(layout.data, 'cluster.sqlite');
  if (!existsSync(db)) return { available: false, reason: 'cluster.sqlite not found' };
  if (clusterId === null) return { available: true };
  const parsed: JsonObject = { available: true };
  let ledger: Ledger;
  try {
    ledger = openLedger(db);
  } catch (error) {
    return { available: false, reason: messageOf(error) };
  }
  const all = (sql: string, ...args: SQLInputValue[]): LedgerRow[] => {
    const rows = ledger.all(sql, ...args);
    if (!rows.every(isLedgerRow)) throw new Error('ledger query returned an unsupported SQLite scalar');
    // Match the former JSON projection, not the SQLite driver's null-prototype objects.
    return rows.map(row => ({ ...row }));
  };
  const cluster = clusterId;
  try {
    parsed.clusters = all('SELECT id,status,revision,limits,budget,declared_limits FROM clusters WHERE id=?', cluster);
    parsed.usage = all("SELECT COUNT(*) AS requests, SUM(COALESCE(total_tokens,0)) AS total_tokens, SUM(COALESCE(prompt_tokens,0)) AS prompt_tokens, SUM(COALESCE(completion_tokens,0)) AS completion_tokens, SUM(COALESCE(cached_tokens,0)) AS cached_tokens, SUM(COALESCE(reasoning_tokens,0)) AS reasoning_tokens, SUM(CASE WHEN status='UNKNOWN' THEN 1 ELSE 0 END) AS unknown_requests, SUM(COALESCE(overshoot,0)) AS overshoot FROM usage_receipts WHERE cluster_id=?", cluster)[0];
    parsed.usage_by_role = all('SELECT role,kind,COUNT(*) AS c,SUM(COALESCE(total_tokens,0)) AS tokens FROM usage_receipts WHERE cluster_id=? GROUP BY role,kind', cluster);
    parsed.usage_by_agent = all("SELECT agent_id, role, kind, COUNT(*) AS c, SUM(CASE WHEN status<>'NOT_SENT' THEN 1 ELSE 0 END) AS sent FROM usage_receipts WHERE cluster_id=? GROUP BY agent_id, role, kind", cluster);
    parsed.usage_states = all('SELECT status, COUNT(*) AS c FROM usage_receipts WHERE cluster_id=? GROUP BY status', cluster);
    parsed.usage_rows = all('SELECT request_id,agent_id,role,kind,status,created,settled FROM usage_receipts WHERE cluster_id=? ORDER BY created,request_id', cluster);
    parsed.usage_unknown_without_note = all("SELECT COUNT(*) AS c FROM usage_receipts WHERE cluster_id=? AND status='UNKNOWN' AND (note IS NULL OR note='')", cluster)[0]?.c;
    parsed.transactions_by_status = all('SELECT status,COUNT(*) AS c FROM transactions WHERE cluster_id=? GROUP BY status', cluster);
    parsed.transactions_detail = all('SELECT id,node_id,status,revision FROM transactions WHERE cluster_id=? ORDER BY created,id', cluster);
    parsed.agents = all("SELECT COUNT(*) AS c, SUM(CASE WHEN status<>'TERMINATED' THEN 1 ELSE 0 END) AS live, SUM(CASE WHEN turns>0 THEN 1 ELSE 0 END) AS activated, SUM(turns) AS turns FROM agents WHERE cluster_id=?", cluster)[0];
    parsed.agent_sessions = all('SELECT id,role,node_id,session_id,status,turns FROM agents WHERE cluster_id=?', cluster);
    parsed.allocations = all('SELECT id,agent_id,transaction_id,node_id,write_scope,write_scope_canonical,status,created FROM allocations WHERE cluster_id=?', cluster);
    parsed.agents_by_role = all('SELECT role,COUNT(*) AS c,SUM(CASE WHEN turns>0 THEN 1 ELSE 0 END) AS activated FROM agents WHERE cluster_id=? GROUP BY role', cluster);
    parsed.nodes = all("SELECT COUNT(*) AS c, MAX(depth) AS max_depth, SUM(CASE WHEN kind='management' THEN 1 ELSE 0 END) AS management FROM nodes WHERE cluster_id=?", cluster)[0];
    parsed.events = all('SELECT COUNT(*) AS c FROM events WHERE cluster_id=?', cluster)[0];
    parsed.event_seq = all('SELECT MAX(seq) AS seq FROM events WHERE cluster_id=?', cluster)[0]?.seq ?? null;
    parsed.leases = all('SELECT COUNT(*) AS c FROM leases WHERE cluster_id=?', cluster)[0];
    parsed.lease_rows = all('SELECT id,cluster_id,agent_id,node_id,purpose,epoch,expires,event_upper_bound,created FROM leases WHERE cluster_id=? ORDER BY id', cluster);
    parsed.effects = all('SELECT status,COUNT(*) AS c FROM effects WHERE cluster_id=? GROUP BY status', cluster);
    parsed.audits = all('SELECT kind,decision,COUNT(*) AS c FROM audits WHERE cluster_id=? GROUP BY kind,decision', cluster);
    parsed.issues = all('SELECT status,COUNT(*) AS c,SUM(corrections) AS corrections FROM issues WHERE cluster_id=? GROUP BY status', cluster);
    parsed.deliveries = all('SELECT status,COUNT(*) AS c FROM recipients WHERE message_id IN (SELECT id FROM messages WHERE cluster_id=?) GROUP BY status', cluster);
    parsed.budget_refusals = all("SELECT COUNT(*) AS c FROM events WHERE cluster_id=? AND type IN ('budget-refused','tool-call-refused')", cluster)[0]?.c;
    parsed.structured_budget_refusals = all("SELECT json_extract(data,'$.scope') AS scope, json_extract(data,'$.dimension') AS dimension, json_extract(data,'$.agent_id') AS agent_id FROM events WHERE cluster_id=? AND type='budget-refused'", cluster);
    parsed.blockers = all("SELECT json_extract(data,'$.code') AS code, json_extract(data,'$.reason') AS reason FROM events WHERE cluster_id=? AND type IN ('cluster-blocked','node-blocked')", cluster);
    parsed.blocked_reason = all("SELECT json_extract(data,'$.reason') AS reason FROM events WHERE cluster_id=? AND type='cluster-blocked' ORDER BY seq DESC LIMIT 1", cluster)[0]?.reason ?? null;
    parsed.duplicate_accepts = all("SELECT COUNT(*) AS c FROM (SELECT json_extract(data,'$.transaction_id') AS t FROM events WHERE cluster_id=? AND type='result-accepted' GROUP BY t HAVING COUNT(*)>1)", cluster)[0]?.c;
    parsed.duplicate_charges = all('SELECT COUNT(*) AS c FROM (SELECT request_id FROM usage_receipts WHERE cluster_id=? GROUP BY request_id HAVING COUNT(*)>1)', cluster)[0]?.c;
    parsed.double_leases = all('SELECT COUNT(*) AS c FROM (SELECT agent_id FROM leases WHERE cluster_id=? GROUP BY agent_id HAVING COUNT(*)>1)', cluster)[0]?.c;
    // Derive concurrency from real recorded intervals, never from configured limits.
    const maxOverlap = (rows: readonly Record<string, unknown>[]): number => {
      const points: [number, number][] = [];
      for (const row of rows) {
        const start = asNumber(row.created);
        const end = asNumber(row.settled);
        if (start === null || end === null) continue;
        points.push([start, 1], [Math.max(start, end), -1]);
      }
      points.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
      let live = 0;
      let peak = 0;
      for (const [, delta] of points) {
        live += delta;
        peak = Math.max(peak, live);
      }
      return peak;
    };
    const receipts = all('SELECT created, settled FROM usage_receipts WHERE cluster_id=?', cluster);
    parsed.max_llm_inflight = receipts.length ? maxOverlap(receipts) : null;
    const turnEvents = all("SELECT type,data,at FROM events WHERE cluster_id=? AND type IN ('turn-start','turn-end') ORDER BY seq", cluster);
    const openTurns = new Map<string, number>();
    const turnIntervals: { created: number; settled: number }[] = [];
    for (const row of turnEvents) {
      const text = asString(row.data);
      if (text === null) continue;
      let agentId: string | null;
      try { agentId = asString(asObject(JSON.parse(text))?.agent_id); } catch { continue; }
      const at = asNumber(row.at);
      if (agentId === null || at === null) continue;
      if (row.type === 'turn-start') openTurns.set(agentId, at);
      else {
        const started = openTurns.get(agentId);
        if (started !== undefined) {
          turnIntervals.push({ created: started, settled: at });
          openTurns.delete(agentId);
        }
      }
    }
    const lastEventAt = asNumber(all('SELECT MAX(at) AS at FROM events WHERE cluster_id=?', cluster)[0]?.at);
    for (const start of openTurns.values()) turnIntervals.push({ created: start, settled: lastEventAt ?? start });
    parsed.turn_events = turnEvents.length;
    parsed.max_resident_turns = turnIntervals.length ? maxOverlap(turnIntervals) : null;
    const allocated: string[][] = [];
    for (const row of all("SELECT write_scope_canonical FROM allocations WHERE cluster_id=? AND status='ACTIVE'", cluster)) {
      const text = asString(row.write_scope_canonical);
      if (text === null) continue;
      let decoded: unknown;
      try { decoded = JSON.parse(text); } catch { continue; }
      if (!Array.isArray(decoded) || decoded.length === 0) continue;
      const paths: string[] = [];
      for (const path of decoded) {
        if (typeof path !== 'string') throw new Error('invalid persisted write scope');
        paths.push(path);
      }
      allocated.push(paths);
    }
    let overlaps = 0;
    for (const [index, first] of allocated.entries()) {
      for (const second of allocated.slice(index + 1)) {
        for (const a of first) for (const b of second) {
          if (a === b || a.startsWith(b.endsWith('/') ? b : `${b}/`) || b.startsWith(a.endsWith('/') ? a : `${a}/`)) overlaps += 1;
        }
      }
    }
    parsed.granted_scope_overlaps = overlaps;
    parsed.allocations_with_scope = allocated.length;
    parsed.terminal_transactions = all("SELECT COUNT(*) AS c FROM transactions WHERE cluster_id=? AND status IN ('ACCEPTED','FAILED','CANCELLED','SUPERSEDED','BLOCKED')", cluster)[0]?.c;
    parsed.total_transactions = all('SELECT COUNT(*) AS c FROM transactions WHERE cluster_id=?', cluster)[0]?.c;
    parsed.blocked_nodes = all("SELECT COUNT(*) AS c FROM nodes WHERE cluster_id=? AND status='BLOCKED'", cluster)[0]?.c;
    parsed.write_capable_calls = all("SELECT COUNT(*) AS c FROM effects WHERE cluster_id=? AND tool IN ('write','edit','bash')", cluster)[0]?.c;
    parsed.write_scope_refusals = all("SELECT COUNT(*) AS c FROM events WHERE cluster_id=? AND type='write-refused'", cluster)[0]?.c;
    parsed.write_allocations = all('SELECT agent_id, write_scope, write_scope_canonical FROM allocations WHERE cluster_id=?', cluster);
    parsed.write_effects = all("SELECT agent_id, tool, args, status FROM effects WHERE cluster_id=? AND status='SETTLED' AND tool IN ('write','edit')", cluster);
  } catch (error) {
    return { available: false, reason: messageOf(error) };
  } finally {
    ledger.close();
  }
  const clusters = ledgerRows(parsed, 'clusters');
  const clusterRow = clusters[0] ?? {};
  const clusterStatus = typeof clusterRow.status === 'string' ? clusterRow.status : 'UNKNOWN';
  const readJson = (value: unknown): Record<string, unknown> => {
    if (value === null || value === undefined) return {};
    try {
      return asObject(typeof value === 'string' ? JSON.parse(value) : value) ?? {};
    } catch {
      return {};
    }
  };
  // The *declared* limits are the ceiling the run is measured against. A role
  // may lower the live limits mid-run (the Allocator's `set_concurrency`), and
  // comparing a whole run's peak against a limit that was changed after the
  // fact would report a compliant run as a violation.
  const limits = { ...readJson(clusterRow.budget), ...readJson(clusterRow.declared_limits ?? clusterRow.limits) };
  const activeLimit = Number(limits.max_active_agents);
  const llmLimit = Number(limits.max_llm_concurrency);
  const ceilings = {
    active: activeLimit > 0 ? activeLimit : null,
    llm: llmLimit > 0 ? llmLimit : null,
  };
  const totalTransactions = ledgerNumber(parsed, 'total_transactions') ?? 0;
  const terminalTransactions = ledgerNumber(parsed, 'terminal_transactions') ?? 0;
  const unfinished = Math.max(0, totalTransactions - terminalTransactions);
  // A prevented write and an escaped write are different facts: the first is
  // the enforcement holding, the second is the defect. Measured here, from the
  // settled effects and the grants they were supposed to obey.
  const writeAnalysis = writeScopeAnalysis({
    allocations: ledgerRows(parsed, 'write_allocations'),
    effects: ledgerRows(parsed, 'write_effects'),
    workspace: layout.workspace ?? null,
  });
  const maxResidentTurns = ledgerNumber(parsed, 'max_resident_turns');
  const maxLlmInflight = ledgerNumber(parsed, 'max_llm_inflight');
  const aggregateRow = (key: string): LedgerRow => {
    const row = asLedgerRow(parsed[key]);
    if (!row) throw new Error(`ledger ${key}: expected aggregate row`);
    return row;
  };
  return {
    available: true,
    cluster_status: clusterStatus,
    blocked_reason: asString(parsed.blocked_reason) ?? null,
    budget_refusals: ledgerNumber(parsed, 'budget_refusals'),
    structured_budget_refusals: ledgerRows(parsed, 'structured_budget_refusals').filter(entry => entry.scope && entry.dimension),
    blockers: ledgerRows(parsed, 'blockers'),
    usage: ledgerUsage(parsed.usage),
    usage_by_role: ledgerRows(parsed, 'usage_by_role'),
    usage_by_agent: ledgerRows(parsed, 'usage_by_agent'),
    usage_states: ledgerRows(parsed, 'usage_states'),
    usage_rows: ledgerRows(parsed, 'usage_rows'),
    usage_unknown_without_note: ledgerNumber(parsed, 'usage_unknown_without_note') ?? 0,
    transactions_by_status: ledgerRows(parsed, 'transactions_by_status'),
    transactions_detail: ledgerRows(parsed, 'transactions_detail'),
    agents: aggregateRow('agents'),
    agent_sessions: ledgerRows(parsed, 'agent_sessions'),
    allocations: ledgerRows(parsed, 'allocations'),
    allocations_with_scope: ledgerNumber(parsed, 'allocations_with_scope') ?? undefined,
    agents_by_role: ledgerRows(parsed, 'agents_by_role'),
    nodes: aggregateRow('nodes'),
    events: aggregateRow('events'),
    event_seq: ledgerNumber(parsed, 'event_seq'),
    leases: aggregateRow('leases'),
    lease_rows: ledgerRows(parsed, 'lease_rows'),
    effects: ledgerRows(parsed, 'effects'),
    audits: ledgerRows(parsed, 'audits'),
    issues: ledgerRows(parsed, 'issues'),
    deliveries: ledgerRows(parsed, 'deliveries'),
    duplicate_accepts: ledgerNumber(parsed, 'duplicate_accepts') ?? 0,
    duplicate_charges: ledgerNumber(parsed, 'duplicate_charges') ?? 0,
    double_leases: ledgerNumber(parsed, 'double_leases') ?? 0,
    // `null` means "not measured in this run"; it is never reported as zero.
    // A proven escape is a failure even when other calls could not be checked;
    // only a clean-but-incomplete result is UNKNOWN. Three states, named: a run
    // that never admitted a write-capable call did not exercise the invariant
    // at all, which is a different fact from a run that could not check one.
    cross_scope_writes: writeAnalysis.escapes.length ? writeAnalysis.escapes.length
      : writeAnalysis.settled_writes === 0 ? null
        : writeAnalysis.unmeasured ? null : 0,
    cross_scope_writes_state: writeAnalysis.escapes.length ? 'measured'
      : writeAnalysis.settled_writes === 0 ? 'not_exercised'
        : writeAnalysis.unmeasured ? 'unknown' : 'measured',
    settled_writes: writeAnalysis.settled_writes,
    write_scope_refusals: ledgerNumber(parsed, 'write_scope_refusals'),
    write_scope_checked: writeAnalysis.checked,
    granted_scope_overlaps: ledgerNumber(parsed, 'granted_scope_overlaps'),
    write_capable_calls: ledgerNumber(parsed, 'write_capable_calls'),
    unfinished_at_stop: unfinished,
    // Work left when the cluster was *stopped* by a declared limit is the
    // documented outcome; work left behind by a cluster that claims
    // COMPLETED is a lost transaction.
    lost_transactions: clusterStatus === 'COMPLETED' ? unfinished : 0,
    // Compare against the limits the cluster recorded for itself; without
    // them the ceiling is unmeasured rather than assumed.
    resident_handles_over_limit: maxResidentTurns === null || !ceilings.active
      ? null : maxResidentTurns > ceilings.active,
    llm_inflight_over_limit: maxLlmInflight === null || !ceilings.llm
      ? null : maxLlmInflight > ceilings.llm,
    max_resident_turns: maxResidentTurns,
    max_llm_inflight: maxLlmInflight,
    ceilings,
    write_allocations: ledgerRows(parsed, 'write_allocations'),
    write_effects: ledgerRows(parsed, 'write_effects'),
    terminal_transactions: terminalTransactions,
    total_transactions: totalTransactions,
    blocked_nodes: ledgerNumber(parsed, 'blocked_nodes') ?? undefined,
    turn_events: ledgerNumber(parsed, 'turn_events') ?? undefined,
  };
}

/** Validate the raw SQLite scalar boundary without trusting a caller's row type. */
function isLedgerRow(value: unknown): value is LedgerRow {
  const record = asObject(value);
  return record !== null && Object.values(record).every(item => item === null
    || typeof item === 'string' || (typeof item === 'number' && Number.isFinite(item)));
}

function asLedgerRow(value: unknown): LedgerRow | null {
  return isLedgerRow(value) ? value : null;
}

/** Preserve every queried row; an invalid row cannot become missing evidence. */
function ledgerRows(source: JsonObject, key: string): LedgerRow[] {
  const list: unknown = source[key];
  if (!Array.isArray(list)) throw new Error(`ledger ${key}: expected rows`);
  if (!list.every(isLedgerRow)) throw new Error(`ledger ${key}: unsupported row`);
  return list;
}

/** One numeric field of the parsed ledger, or `null`. */
function ledgerNumber(source: JsonObject, key: string): number | null {
  const value = source[key];
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

/** The usage aggregate row, rebuilt field by field from the parsed ledger. */
function ledgerUsage(value: unknown): LedgerUsage | undefined {
  const row = asLedgerRow(value);
  if (!row) return undefined;
  const field = (key: string): number | null => {
    const value = row[key];
    if (value === null) return null;
    if (typeof value !== 'number' || !Number.isFinite(value)) throw new Error(`ledger usage ${key}: expected a number or null`);
    return value;
  };
  const requests = field('requests');
  if (requests === null) throw new Error('ledger usage requests: COUNT cannot be null');
  return {
    requests,
    total_tokens: field('total_tokens'),
    prompt_tokens: field('prompt_tokens'),
    completion_tokens: field('completion_tokens'),
    cached_tokens: field('cached_tokens'),
    reasoning_tokens: field('reasoning_tokens'),
    unknown_requests: field('unknown_requests'),
    overshoot: field('overshoot'),
  };
}

/**
 * Per-request evidence, without the whole prompt: who was addressed, which
 * script branch answered, what the answer contained, and whether it was held.
 * The Authorization header is never recorded at all.
 */
function summarizeMockRequests(mock: MockModelHandle): MockRequestSummary[] {
  return mock.requests.map(entry => ({
    seq: entry.seq, kind: entry.kind, role: entry.role, node_id: entry.node_id, agent_id: entry.agent_id,
    transaction_id: entry.transaction_id, barrier: entry.barrier,
    authorized: entry.authorized, max_tokens_field: entry.request_shape?.max_tokens_field ?? null,
    tool_calls: (entry.response?.tool_calls ?? []).map(call => call.name),
    finish_reason: entry.response?.finish_reason ?? null,
    usage: entry.response?.usage ?? null,
  }));
}

/** One file the isolated host wrote under its own session directory. */
interface SessionFile {
  path: string;
  bytes: number;
}

function listSessions(layout: RunLayout): SessionFile[] {
  const root = join(layout.home, 'sessions');
  if (!existsSync(root)) return [];
  return walk(root).slice(0, 500);
}

function walk(root: string): SessionFile[] {
  const out: SessionFile[] = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    const full = join(root, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else out.push({ path: full, bytes: statSync(full).size });
  }
  return out;
}

/** Run only when executed directly: importing this module must have no effect. */
const invokedDirectly = (): boolean => {
  const entry = process.argv[1];
  if (!entry) return false;
  const self = fileURLToPath(import.meta.url);
  try {
    return self === resolve(entry);
  } catch {
    // A missing import must not turn the entry point into a silent no-op.
    return self.endsWith(entry);
  }
};

if (invokedDirectly()) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
