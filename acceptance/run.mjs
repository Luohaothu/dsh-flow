const MODE_LIMITS = {
  hierarchical: {},
  flat: { max_depth: 1, max_children: 32 },
  single: { max_depth: 1, max_children: 1 },
};

async function main() {
  const args = parseArgs(process.argv.slice(2));
  for (const key of ['budget-scale', 'max-role-turns']) {
    if (args[key] !== undefined && (!Number.isSafeInteger(args[key]) || args[key] < 1)) {
      throw new Error(`--${key} must be a positive integer`);
    }
  }
  const caseDef = loadCase(args.case);
  const runIds = args.mode === 'all' ? ['single', 'flat', 'hierarchical'] : [args.mode ?? 'hierarchical'];
  const summaries = [];
  for (const mode of runIds) {
    const runId = runIds.length > 1 ? `${args['run-id']}-${mode}` : args['run-id'];
    summaries.push(await runOnce({ args, caseDef, mode, runId }));
  }
  const failed = summaries.filter(summary => summary.scenario_status !== 'PASSED');
  console.log(JSON.stringify({ case: caseDef.id, runs: summaries }, null, 2));
  if (failed.length && !args['keep-failed']) process.exitCode = 1;
}

function parseArgs(argv) {
  const out = { mode: 'hierarchical', 'timeout-ms': undefined };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (!token.startsWith('--')) continue;
    const key = token.slice(2);
    const next = argv[index + 1];
    if (next === undefined || next.startsWith('--')) out[key] = true;
    else {
      out[key] = /^-?\d+$/.test(next) ? Number(next) : next;
      index += 1;
    }
  }
  return out;
}

/**
 * The only case-level environment a case may set. Isolation (`HOME`, `TMPDIR`,
 * `DSH_HOME`), the data directory, the workspace and the model route are owned
 * by the runner: a case that could redirect them would stop being a case and
 * start being a different experiment.
 */
export { CASE_ENV_KEYS };

export function validateCaseEnv(caseDef) {
  const env = caseDef.env ?? {};
  if (typeof env !== 'object' || Array.isArray(env)) throw new Error(`case ${caseDef.id}: env must be an object`);
  const unknown = Object.keys(env).filter(key => !CASE_ENV_KEYS.includes(key));
  if (unknown.length) {
    throw new Error(`case ${caseDef.id}: env may only set ${CASE_ENV_KEYS.join(', ')}; got ${unknown.join(', ')}`);
  }
  for (const [key, value] of Object.entries(env)) {
    if (typeof value !== 'string' || !value) throw new Error(`case ${caseDef.id}: env.${key} must be a non-empty string`);
  }
  return env;
}

export function modelRouteFromEnv(env = process.env) {
  return {
    baseURL: env.FLOW_MODEL_BASE_URL ?? env.FLOW_QWEN_BASE_URL ?? 'http://127.0.0.1:8000/v1',
    model: env.FLOW_MODEL_ID ?? env.FLOW_QWEN_MODEL ?? 'Qwen3.8-27B-FP8',
    provider: env.FLOW_MODEL_PROVIDER ?? 'local-sglang',
  };
}

function hashText(text) {
  return `sha256:${createHash('sha256').update(text).digest('hex')}`;
}

function hashFile(path) {
  return existsSync(path) ? hashText(readFileSync(path)) : null;
}

/** One digest over every file of a source tree, plus its file count. */
function hashTree(root) {
  if (!existsSync(root)) return { digest: null, files: 0 };
  const files = walk(root).map(entry => ({ path: entry.path, digest: hashFile(entry.path) }))
    .sort((a, b) => a.path.localeCompare(b.path));
  const digest = hashText(files.map(entry => `${entry.path}:${entry.digest}`).join('\n'));
  return { digest, files: files.length };
}

/**
 * The code fingerprint of one run: the plugin sources, both built entry points,
 * the case file and every patch the host loads. It is what makes "the same
 * build" a checkable claim instead of an assumption.
 */
/**
 * Which part of the build fingerprint moved between two samples, or null when
 * the run describes one single build. Kept as a named function because the
 * claim "this report describes one build" is only checkable if the rule that
 * decides it is itself checkable.
 */
export function buildDrift(before, after) {
  if (!before || !after) return 'the fingerprint was never taken';
  const changed = [];
  for (const key of ['plugin_source', 'lib_index', 'lib_client', 'acceptance_source', 'case_file']) {
    if (JSON.stringify(before[key] ?? null) !== JSON.stringify(after[key] ?? null)) changed.push(key);
  }
  const beforePatches = JSON.stringify(before.patches ?? []);
  if (beforePatches !== JSON.stringify(after.patches ?? [])) changed.push('patches');
  return changed.length ? changed.join(', ') : null;
}

export function computeBuildHashes(caseDef, patches) {
  return {
    plugin_source: hashTree(join(PROJECT_ROOT, 'adapter/src')),
    lib_index: hashFile(join(PROJECT_ROOT, 'lib/index.js')),
    lib_client: hashFile(join(PROJECT_ROOT, 'lib/client.js')),
    // The acceptance code is part of the experiment: a checker or a scenario
    // that changed mid-run would make the report describe two different tests.
    acceptance_source: hashTree(join(PROJECT_ROOT, 'acceptance')),
    case_file: caseDef.id ? hashFile(join(CASES_DIR, `${caseDef.id}.json`)) : null,
    patches: (patches ?? []).map(path => ({ path, digest: hashFile(path) })),
  };
}

function loadCase(name) {
  if (!name) throw new Error('--case is required');
  const path = join(CASES_DIR, `${name}.json`);
  if (!existsSync(path)) throw new Error(`unknown case ${JSON.stringify(name)}; expected a file at ${path}`);
  return { id: name, ...JSON.parse(readFileSync(path, 'utf8')) };
}

async function runOnce({ args, caseDef, mode, runId }) {
  const layout = createRunLayout(ARTIFACTS_ROOT, runId);
  const profile = `dsh-flow-${runId}`.replace(/[^A-Za-z0-9._-]/g, '-');
  if (args.mock) {
    // A mock run fixes the model *input*. An extra model overlay or a
    // budget/turn multiplier would make the verdict describe something other
    // than the frozen fixture the case declares.
    for (const forbidden of ['profile-patch', 'budget-scale', 'max-role-turns']) {
      if (args[forbidden] !== undefined) {
        throw new Error(`--mock refuses --${forbidden}: the mock suite runs the frozen fixture, not a scaled experiment`);
      }
    }
  }
  const mock = args.mock ? await startMockModel({ modelId: MOCK_MODEL_ID }) : null;
  const modelRoute = mock
    ? { baseURL: mock.baseURL, model: MOCK_MODEL_ID, provider: MOCK_PROVIDER }
    : modelRouteFromEnv();
  const patches = (caseDef.patches ?? [caseDef.patch ?? 'examples/cluster.patch.yml'])
    .concat(args['profile-patch'] ? [args['profile-patch']] : [])
    .map(entry => resolve(PROJECT_ROOT, entry));
  if (mock) {
    const overlay = join(layout.root, 'mock-model.patch.yml');
    writeFileSync(overlay, mockPatchText(mock.baseURL));
    patches.push(overlay);
  }
  const patch = patches[0];
  const caseEnv = validateCaseEnv(caseDef);
  // The build fingerprint is taken before anything runs and re-checked at the
  // end: a report whose code changed mid-run describes no single build.
  const budgetScale = args['budget-scale'] ?? 1;
  const settleTimeoutMs = args['timeout-ms'] ?? (caseDef.timeout_ms ?? 3_600_000) * budgetScale;
  if (!Number.isSafeInteger(settleTimeoutMs) || settleTimeoutMs < 1) throw new Error('settle timeout must be a positive safe integer');
  const buildHashesAtStart = computeBuildHashes(caseDef, patches);

  const started = Date.now();
  const report = {
    run_id: runId,
    case: caseDef.id,
    mode,
    title: caseDef.title,
    started_at: new Date(started).toISOString(),
    validation_mode: mock ? 'mock-api' : 'live-model',
    model_route: modelRoute,
    patch,
    patches,
    profile,
    paths: { ...layout },
    build_hashes: buildHashesAtStart,
    input_hashes: {},
    mechanism_pass: 'UNKNOWN',
    scenario_status: 'UNKNOWN',
    quality_checks: [],
    failure_class: null,
    notes: [],
    ...(budgetScale !== 1 || args['max-role-turns'] !== undefined
      ? { experiment: { budget_scale: budgetScale, max_role_turns: args['max-role-turns'] ?? null, settle_timeout_ms: settleTimeoutMs } }
      : {}),
  };

  const workspace = layout.workspace;
  const preparation = prepareWorkspace(caseDef, workspace, layout, mode);
  report.preparation = preparation;
  // Two different fingerprints, named for what they fingerprint: `input_hashes`
  // is the data the run consumed, `build_hashes` is the code that ran.
  report.input_hashes = preparation.source_hashes ?? {};

  const checksModule = await loadChecksModule(caseDef.id);
  const baselineArgs = { caseDef, mode, layout, workspace, report, args };
  if (checksModule?.before) report.baseline = await checksModule.before(baselineArgs);

  ensureProfile(layout.home, profile, { bundles: WEB_PROFILE_BUNDLES });
  // Chromium's SingletonSocket uses a Unix-domain pathname with a hard
  // length cap. Keep the actual scratch files under this isolated run, but
  // expose a short, per-run TMPDIR alias to the browser-capable host.
  const browserTmpAlias = caseDef.capabilities?.includes('browser')
    ? join(tmpdir(), `dsh-${randomUUID().slice(0, 12)}`) : null;
  if (browserTmpAlias) {
    symlinkSync(layout.tmp, browserTmpAlias, 'dir');
    report.notes.push(`browser TMPDIR ${browserTmpAlias} -> ${layout.tmp}`);
  }
  const env = buildHostEnv({
    home: layout.home, tmpdir: browserTmpAlias ?? layout.tmp, dataDir: layout.data, workspace, modelRoute,
    modelApiKey: mock ? MOCK_API_KEY : process.env.FLOW_MODEL_API_KEY,
    extra: caseEnv,
  });
  if (mock) {
    report.mock = { scenario: `mock:${caseDef.id}`, base_url: mock.baseURL, model: MOCK_MODEL_ID };
  }

  let host = new DshHost({
    profile,
    patches,
    cwd: workspace,
    env,
    logPath: join(layout.logs, 'host.log'),
  });

  const events = [];
  let snapshot = null;
  let single = null;
  let failure = null;
  try {
    await host.start();
    report.notes.push(`host booted (pid ${host.child.pid}) with profile ${profile}`);
    try {
      await host.waitForWebUrl(120_000);
      report.web_url = host.webUrl;
    } catch (error) {
      report.notes.push(`web URL not observed: ${error.message}`);
    }
    // The host's own web URL is known before the cluster starts, so a case can
    // name it: the browser case drives the host's authenticated page instead of
    // depending on the public internet.
    const spec = buildSpec(caseDef, workspace, mode, runId, args['dataset-limit'], { webUrl: report.web_url ?? null });
    // A concurrency ladder changes exactly one knob at a time.
    if (args['max-llm-concurrency'] !== undefined) {
      spec.limits = { ...spec.limits, max_llm_concurrency: Number(args['max-llm-concurrency']) };
      spec.budget = { ...spec.budget, max_active_agents: spec.budget.max_active_agents ?? spec.limits.max_active_agents };
    }
    if (args['max-active-agents'] !== undefined) {
      spec.limits = { ...spec.limits, max_active_agents: Number(args['max-active-agents']) };
    }
    assertTierBudget(spec);
    delete spec.generated_tier;
    if (budgetScale !== 1) {
      // The case remains an immutable baseline. The effective budget and this
      // override are both written into the report under a new run id; identity
      // and concurrency ceilings stay unchanged.
      for (const dimension of ['tokens', 'model_requests', 'tool_calls', 'wall_time_ms']) {
        const scaled = spec.budget[dimension] * budgetScale;
        if (!Number.isSafeInteger(scaled)) throw new Error(`scaled ${dimension} is not a safe integer`);
        spec.budget[dimension] = scaled;
      }
    }
    if (args['max-role-turns'] !== undefined) spec.limits.max_role_turns = args['max-role-turns'];
    // Every fixture id is run-scoped before anything is written, so a collision
    // is a clear pre-flight error instead of a half-populated database.
    const namespaced = namespaceFixtures(spec, runId);
    report.fixture_id_map = namespaced.map;
    report.spec = namespaced.spec;
    if (mock) {
      // Bound after namespacing and before `start`: the scenario names the same
      // transactions the case does, and a request that arrives before a script
      // exists is a fixture error rather than a default answer.
      const scenario = buildScenario({
        caseId: caseDef.id, layout, workspace, fixtureIds: namespaced.map, runId, limits: namespaced.spec.limits,
      });
      mock.setScenario(scenario);
      report.mock.scenario = scenario.name;
    }

    if (mode === 'single') {
      const singleTurn = await host.request('single', undefined, {
        objective: namespaced.spec.objective,
        workspace,
        capabilities: namespaced.spec.capabilities,
        budget: namespaced.spec.budget,
        initial_transactions: namespaced.spec.initial_transactions,
        acceptance_criteria: namespaced.spec.acceptance_criteria,
      }, settleTimeoutMs);
      single = singleTurn;
      report.single = singleTurn;
      // The control run is a cluster of its own: report it as such so the
      // ledger and the mechanism gate are computed from the same source.
      report.cluster_id = singleTurn.cluster_id;
    } else {
      const created = await host.request('start', undefined, namespaced.spec, 120_000);
      report.cluster_id = created.cluster.id;
      if (mock && caseDef.scale_fixture?.concurrency_probe) {
        // Hold exactly `max_llm_concurrency` Worker requests open at once and
        // watch the wire: while they are held, a request beyond the ceiling
        // would have to arrive here. Nothing else can prove the ceiling is
        // enforced rather than merely reported.
        const ceiling = Number(namespaced.spec.limits.max_llm_concurrency ?? 2);
        await mock.waitUntilHeld(ceiling, { barrier: 'scale-concurrency', timeoutMs: 120_000 });
        const beforeProbe = mock.requests.length;
        const probeWindowMs = Number(caseDef.scale_fixture.concurrency_probe_window_ms ?? 3000);
        await new Promise(resolvePromise => setTimeout(resolvePromise, probeWindowMs));
        report.concurrency_probe = {
          ceiling,
          held_simultaneously: mock.heldCount('scale-concurrency'),
          requests_while_held: mock.requests.length - beforeProbe,
          window_ms: probeWindowMs,
        };
        mock.release('scale-concurrency');
      }
      if (caseDef.live_first && checksModule?.live) {
        try {
          report.live_checks = await checksModule.live({ caseDef, mode, layout, workspace, report, host, env, args, mock });
        } catch (error) {
          report.live_checks = { checks: [], error: String(error?.message ?? error) };
          report.notes.push(`live checks failed: ${error?.message ?? error}`);
        }
      }
      if (caseDef.recovery?.require_restart) {
        const outcome = await restartMidFlight({
          host, caseDef, layout, report, args, workspace, profile, patches, env, mock,
        });
        host = outcome.host;
        report.restart = outcome.facts;
      }
      await host.request('settle', created.cluster.id, {
        timeout_ms: settleTimeoutMs,
        poll_ms: 400,
      }, settleTimeoutMs + 120_000);
      snapshot = await host.request('read', created.cluster.id, { include_events: false, limit: 500 }, 120_000);
      events.push(...await drainEvents(host, created.cluster.id));
      report.report = await host.request('report', created.cluster.id, {}, 120_000);
    }
    // Checks that need the live host (the panel, the authenticated route) run
    // before shutdown; everything else runs afterwards from durable state.
    if (!caseDef.live_first && checksModule?.live) {
      try {
        report.live_checks = await checksModule.live({ caseDef, mode, layout, workspace, report, host, env, args, snapshot, events, mock });
      } catch (error) {
        report.live_checks = { checks: [], error: String(error?.message ?? error) };
        report.notes.push(`live checks failed: ${error?.message ?? error}`);
      }
    }
  } catch (error) {
    failure = { message: String(error?.message ?? error), stack: String(error?.stack ?? '') };
    report.failure_class = 'MECHANISM';
  } finally {
    if (!args['keep-host']) {
      const stopped = await host.stop();
      report.host_exit = stopped;
    }
    if (browserTmpAlias && !args['keep-host']) unlinkSync(browserTmpAlias);
    if (mock && !args['keep-host']) {
      try {
        report.mock_fixture = { ok: true, ...mock.assertComplete() };
      } catch (error) {
        // A scenario that could not recognise a request, held one that never
        // released, or saw a protocol drift is an *acceptance facility* defect:
        // it fails the run rather than being reported as a plugin outcome.
        report.mock_fixture = { ok: false, problem: String(error?.message ?? error), errors: [...mock.errors] };
      }
      report.mock_requests = summarizeMockRequests(mock);
      report.mock_concurrency = {
        peak_concurrent_requests: mock.peakConcurrency(),
        requests: mock.requests.length,
      };
      writeFileSync(join(layout.root, 'mock-requests.json'), `${JSON.stringify(mock.requests.map(entry => ({
        seq: entry.seq, at: entry.at, model: entry.model, kind: entry.kind, role: entry.role,
        node_id: entry.node_id, agent_id: entry.agent_id, transaction_id: entry.transaction_id,
        tools: entry.tools, authorized: entry.authorized, request_shape: entry.request_shape,
        digest_source: entry.classified?.digest_source ?? null,
        barrier: entry.barrier, held: entry.held, response: entry.response ?? null,
        opened_at: entry.opened_at ?? null, closed_at: entry.closed_at ?? null,
        prompt_preview: String(entry.classified?.userText ?? '').slice(0, 1200),
        last_tool_name: entry.classified?.lastToolName ?? null,
        last_tool_result: entry.classified?.lastToolResult === null || entry.classified?.lastToolResult === undefined
          ? null : String(entry.classified.lastToolResult).slice(0, 600),
        // An unrecognised request is the one case where the full message shape
        // is the evidence needed to fix the fixture; it is never the normal
        // record, which would store the whole session on every run.
        ...(entry.kind === 'unknown' || entry.diagnostic ? {
          diagnostics: (entry.body?.messages ?? []).map(message => ({
            role: message.role,
            tool_calls: Array.isArray(message.tool_calls) ? message.tool_calls.map(call => call.function?.name) : undefined,
            text: (typeof message.content === 'string' ? message.content
              : (message.content ?? []).map(part => part?.text ?? '').join('\n')).slice(0, 2000),
          })),
        } : {}),
      })), null, 2)}\n`);
      await mock.close();
    }
  }

  report.failure = failure;

  const ledger = readStoneLedger(layout, report.cluster_id ?? null);
  report.ledger = ledger;

  // The clock and the structured limit evidence are measured *before* the case's
  // checks, because those checks derive their own verdict from them.
  measureRun(report, {
    startedAt: started,
    budget: report.spec?.budget ?? {},
    usage: ledger.usage ?? {},
    clusterReason: ledger.blocked_reason ?? null,
    refusals: ledger.structured_budget_refusals ?? [],
    buildHashes: computeBuildHashes(caseDef, patches),
  });
  const checkResult = await runChecks({ caseDef, mode, layout, workspace, report, single, snapshot, events, host, env, args });
  report.quality_checks = checkResult.checks;
  report.scenario_status = checkResult.scenario_status;
  // A fixture that could not answer a request, or held one that never released,
  // is an acceptance-facility failure. It is never allowed to pass as a plugin
  // outcome, and it is never relabelled as a model-quality result.
  if (report.mock_fixture && report.mock_fixture.ok === false) {
    report.scenario_status = 'FAILED';
    report.failure_class = 'FIXTURE';
  }
  // Classification is finalised before the mechanism verdict is computed, so a
  // check-level MECHANISM failure can never be relabelled by the budget branch.
  // Only a class the checks *derived* is carried here: stamping MODEL_OUTPUT on
  // every unclassified failure before the limit facts were consulted labelled a
  // budget-limited run as a model failure (measured: 16 structured refusals and a
  // `MODEL_OUTPUT` class on the same report).
  if (report.failure_class === null && report.scenario_status === 'FAILED' && checkResult.failure_class) {
    report.failure_class = checkResult.failure_class;
  }
  // The wall clock is *measured here*, before it is classified: passing
  // `report.wall_time_ms` while it is still unset made every wall-time verdict a
  // comparison against zero.
  report.finished_at = new Date().toISOString();
  report.wall_time_ms = Date.now() - started;
  // The same measurement again, now that the checks may have set a class: the
  // measurement is idempotent, and the *class* is what the checks may not
  // overwrite.
  // An explicit budget or wall-time exhaustion is its own verdict: the
  // scenario did not fail because the model was wrong, it stopped because the
  // fixture's own limit was reached.
  const classification = classifyOutcome({
    failureClass: report.failure_class, scenarioStatus: report.scenario_status,
    budget: report.spec?.budget ?? {}, usage: ledger.usage ?? {}, wallTimeMs: report.wall_time_ms,
    clusterReason: ledger.blocked_reason ?? null,
    // Only a *structured* refusal (a persisted budget-refused record with its
    // scope and dimension) is evidence that a limit was really reached. Free
    // text, a near-ceiling ratio or a tool refusal never is.
    refusals: ledger.structured_budget_refusals ?? [],
  });
  report.failure_class = classification.failure_class;
  report.limit_reached = classification.limit_reached;
  report.mechanism_pass = mechanismVerdict(report, ledger);
  if (checkResult.scale_validation) {
    // The plan reads this flag from the report: a tier that did not really run
    // its workers must never be summarised as a verified scale number.
    report.scale_validation = checkResult.scale_validation;
    report.scale_metrics = checkResult.metrics ?? null;
    report.measured_per_file = checkResult.measured_per_file ?? null;
  }
  // A report whose build changed while it ran describes no single build.
  const buildHashesAtEnd = computeBuildHashes(caseDef, patches);
  const drift = buildDrift(report.build_hashes, buildHashesAtEnd);
  report.build_drift = drift;
  if (drift) {
    report.not_comparable = true;
    report.notes.push(`build_hashes changed during the run (${drift}); the report does not describe one build`);
  }

  writeFileSync(join(layout.root, 'report.json'), `${JSON.stringify(report, null, 2)}\n`);
  writeFileSync(join(layout.root, 'events.jsonl'), `${events.map(event => JSON.stringify(event)).join('\n')}\n`);
  writeFileSync(join(layout.root, 'usage.json'), `${JSON.stringify(ledger.usage ?? null, null, 2)}\n`);
  writeFileSync(join(layout.root, 'checks.json'), `${JSON.stringify(checkResult, null, 2)}\n`);
  writeFileSync(join(layout.root, 'sessions.json'), `${JSON.stringify(listSessions(layout), null, 2)}\n`);
  if (snapshot) writeFileSync(join(layout.root, 'state.json'), `${JSON.stringify(snapshot, null, 2)}\n`);

  console.log(`[${runId}] mode=${mode} scenario=${report.scenario_status} mechanism=${report.mechanism_pass} reports=${layout.root}`);
  return {
    run_id: runId,
    mode,
    scenario_status: report.scenario_status,
    mechanism_pass: report.mechanism_pass,
    failure_class: report.failure_class,
    wall_time_ms: report.wall_time_ms,
    cluster_id: report.cluster_id ?? null,
    report: join(layout.root, 'report.json'),
  };
}

/** Poll the durable event stream by cursor until the crash trigger or deadline. */
export async function waitForKillEvent(host, clusterId, killOn, delay, {
  now = Date.now,
  sleep = ms => new Promise(resolvePromise => setTimeout(resolvePromise, ms)),
} = {}) {
  const started = now();
  const deadline = started + delay;
  let since = 0;
  let seen = 0;
  let observedSeq = null;
  let pollError = null;
  let polls = 0;
  while (now() < deadline) {
    polls += 1;
    try {
      const page = await host.request('events', clusterId, { since, limit: 500 }, 30_000);
      const events = page?.events ?? [];
      const matches = events.filter(event => event.type === killOn);
      if (matches.length) {
        seen = matches.length;
        observedSeq = matches[0].seq;
        break;
      }
      if (events.length) since = events[events.length - 1].seq;
      // A full page means there may be more durable history already waiting.
      // Catch up before sleeping so the trigger is not lost behind old events.
      if (events.length === 500) continue;
    } catch (error) {
      // A failed poll must not look like "the window never opened".
      pollError = pollError ?? error.message;
      if (polls > 4) break;
    }
    await sleep(250);
  }
  const trigger = {
    event: killOn, observed: seen, observed_seq: observedSeq, polls, poll_error: pollError,
    cluster_id: clusterId ?? null, observed_at_ms: now() - started,
  };
  if (!seen) {
    trigger.note = pollError
      ? `polling failed (${pollError}); killed on the clock instead`
      : 'the trigger event did not occur before the deadline; killed on the clock instead';
  }
  return trigger;
}

/**
 * Kill the test host mid-flight and restart it against the same DSH_HOME and
 * data directory, capturing the durable facts on both sides of the crash.
 */
async function restartMidFlight({ host, caseDef, layout, report, args, workspace, profile, patches, env, mock = null }) {
  const delay = Number(caseDef.recovery?.kill_after_ms ?? 45_000);
  // A kill-on-event trigger lands the crash *inside* a named window instead of
  // at an arbitrary wall-clock moment. `delivery-flushed` is the one boundary a
  // poll of `messages-injected` cannot reach: the plugin records it after the
  // session is durable and before the delivery is acked.
  const killOn = caseDef.recovery?.kill_on_event ?? args['kill-on-event'] ?? null;
  // A kill-on-hold trigger is stronger than either: the crash lands while a
  // *named identity is holding a live model request*, proven by the fixture
  // that served it rather than inferred from an event poll.
  const killOnHold = caseDef.recovery?.kill_on_hold ?? args['kill-on-hold'] ?? null;
  const before = readStoneLedger(layout, report.cluster_id ?? null);
  if (killOnHold) {
    if (!mock) throw new Error(`case ${caseDef.id} requires --mock for its kill-on-hold trigger`);
    const held = await mock.waitForRequest(entry => entry.held && entry.barrier === killOnHold, { timeoutMs: delay });
    report.kill_trigger = {
      event: 'hold', barrier: killOnHold, observed: 1, observed_seq: null, polls: null,
      cluster_id: report.cluster_id ?? null, request_seq: held.seq, kind: held.kind,
      role: held.role, agent_id: held.agent_id, transaction_id: held.transaction_id,
      observed_at_ms: held.at,
    };
  } else if (killOn) {
    report.kill_trigger = await waitForKillEvent(host, report.cluster_id, killOn, delay);
  }
  const killAtMs = Date.now();
  const stopped = await host.stop({ signal: 'SIGKILL', graceMs: 2000 });
  const atCrash = readStoneLedger(layout, report.cluster_id ?? null);
  // The exact receipts that were dispatched and never settled at the crash: the
  // expected number of UNKNOWN results is this set, not an arbitrary allowance.
  const inFlight = (atCrash.usage_rows ?? []).filter(row => row.settled === null && row.created <= killAtMs);
  await new Promise(resolvePromise => setTimeout(resolvePromise, Number(caseDef.recovery?.restart_delay_ms ?? 2000)));
  const restarted = new DshHost({ profile, patches, cwd: workspace, env, logPath: join(layout.logs, 'host-restart.log') });
  await restarted.start();
  return {
    host: restarted,
    facts: {
      kill_after_ms: delay,
      // The wall clock and the event cursor at the moment of the kill: the
      // crash window is attributed against these, never assumed.
      kill_at_ms: killAtMs,
      event_seq_at_kill: atCrash.event_seq ?? null,
      kill_trigger: report.kill_trigger ?? null,
      exit: stopped,
      usage_at_crash: atCrash.usage,
      usage_before_kill: before.usage,
      accepted_at_crash: atCrash.transactions_by_status,
      uncertain_effects_at_crash: atCrash.effects,
      leases_at_crash: atCrash.lease_rows,
      // Receipts dispatched but unsettled, and the transactions that were not
      // yet terminal: the crash's own account of what it interrupted.
      receipts_in_flight_at_crash: inFlight.map(row => ({
        request_id: row.request_id, agent_id: row.agent_id, role: row.role, kind: row.kind, created: row.created,
      })),
      transactions_open_at_crash: (atCrash.transactions_detail ?? []).filter(row => row.status !== 'ACCEPTED'),
      restarted: true,
    },
  };
}

