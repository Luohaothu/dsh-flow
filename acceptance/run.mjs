#!/usr/bin/env node
/**
 * Acceptance runner.
 *
 * Boots the plugin in a real, isolated DSH profile and drives one case through
 * the host's own IPC channel to `ctx.flow`. Every artifact lands in
 * `.artifacts/<run-id>/`; the report separates mechanism failures from model
 * output quality and environment problems.
 *
 * Usage:
 *   node acceptance/run.mjs --case <case> --run-id <id>
 *     [--mode hierarchical|flat|single|all] [--timeout-ms N]
 *     [--budget-scale N] [--max-role-turns N] [--keep-host]
 */
